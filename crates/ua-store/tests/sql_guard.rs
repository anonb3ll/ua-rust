fn check_counts_baseline(
    baseline_name: &str,
    actual: &BTreeMap<(String, String), usize>,
    baseline: &[(&str, &str, usize)],
) -> Result<(), String> {
    let mut expected: BTreeMap<(String, String), usize> = BTreeMap::new();
    let mut dupes = Vec::new();
    for &(k, r, n) in baseline {
        if expected.insert((k.to_string(), r.to_string()), n).is_some() {
            dupes.push(format!("  {k}/{r}"));
        }
    }
    if !dupes.is_empty() {
        return Err(format!("duplicate entries in {baseline_name}:\n{}", dupes.join("\n")));
    }

    let mut all_keys: BTreeSet<(String, String)> = BTreeSet::new();
    all_keys.extend(actual.keys().cloned());
    all_keys.extend(expected.keys().cloned());

    let mut above = Vec::new();
    let mut below = Vec::new();
    for key in all_keys {
        let got = actual.get(&key).copied().unwrap_or(0);
        let want = expected.get(&key).copied().unwrap_or(0);
        if got > want {
            above.push(format!("  {}/{}: got {got}, baseline {want} (+{})", key.0, key.1, got - want));
        } else if got < want {
            below.push(format!("  {}/{}: got {got}, baseline {want} (-{})", key.0, key.1, want - got));
        }
    }

    if above.is_empty() && below.is_empty() {
        return Ok(());
    }

    let mut msg = format!("{baseline_name} drift detected (see docs/store.md):\n");
    if !above.is_empty() {
        msg.push_str(
            "\nAbove baseline — route new queries through ua-store repositories instead of raising the baseline:\n",
        );
        msg.push_str(&above.join("\n"));
        msg.push('\n');
    }
    if !below.is_empty() {
        msg.push_str(
            "\nBelow baseline — lower the entry in crates/ua-store/tests/sql_guard.rs in the same PR (remove it if 0):\n",
        );
        msg.push_str(&below.join("\n"));
        msg.push('\n');
    }
    Err(msg)
}

fn check_frozen_helpers(
    actual: &BTreeMap<(String, String, String), DetectedHelper>,
    baseline: &[(&str, &str, &str)],
) -> Result<(), String> {
    let expected: BTreeSet<(String, String, String)> =
        baseline.iter().map(|&(k, r, n)| (k.to_string(), r.to_string(), n.to_string())).collect();
    let got: BTreeSet<(String, String, String)> = actual.keys().cloned().collect();

    let added: Vec<String> = got
        .difference(&expected)
        .map(|k| {
            let line = actual.get(k).map(|h| h.line).unwrap_or(0);
            format!("  {}/{}:{} (L{line})", k.0, k.1, k.2)
        })
        .collect();
    let removed: Vec<String> =
        expected.difference(&got).map(|k| format!("  {}/{}:{}", k.0, k.1, k.2)).collect();

    if added.is_empty() && removed.is_empty() {
        return Ok(());
    }

    let mut msg = String::from("FROZEN_HELPERS drift detected (see docs/store.md):\n");
    if !added.is_empty() {
        msg.push_str("\nNew SQL-taking helper(s) forbidden outside ua-store:\n");
        msg.push_str(&added.join("\n"));
        msg.push('\n');
    }
    if !removed.is_empty() {
        msg.push_str(
            "\nRemoved SQL-taking helper(s) — delete these entries from FROZEN_HELPERS in the same PR:\n",
        );
        msg.push_str(&removed.join("\n"));
        msg.push('\n');
    }
    Err(msg)
}

fn check_ua_store_pub_sql_fns(
    actual: &BTreeMap<(String, String), DetectedHelper>,
    baseline: &[(&str, &str)],
) -> Result<(), String> {
    let expected: BTreeSet<(String, String)> =
        baseline.iter().map(|&(r, n)| (r.to_string(), n.to_string())).collect();
    let got: BTreeSet<(String, String)> = actual.keys().cloned().collect();

    let added: Vec<String> = got
        .difference(&expected)
        .map(|k| {
            let line = actual.get(k).map(|h| h.line).unwrap_or(0);
            format!("  ua-store/{}:{} (L{line})", k.0, k.1)
        })
        .collect();
    let removed: Vec<String> =
        expected.difference(&got).map(|k| format!("  ua-store/{}:{}", k.0, k.1)).collect();

    if added.is_empty() && removed.is_empty() {
        return Ok(());
    }

    let mut msg = String::from("FROZEN_UA_STORE_PUB_SQL_FNS drift detected (see docs/store.md):\n");
    if !added.is_empty() {
        msg.push_str("\nPublic SQL-taking function(s) forbidden in ua-store outside schema.rs:\n");
        msg.push_str(&added.join("\n"));
        msg.push('\n');
    }
    if !removed.is_empty() {
        msg.push_str(
            "\nRemoved frozen ua-store SQL fn(s) — delete from FROZEN_UA_STORE_PUB_SQL_FNS in the same PR:\n",
        );
        msg.push_str(&removed.join("\n"));
        msg.push('\n');
    }
    Err(msg)
}

fn check_procedure_constructors(actual: &[(String, String, String, usize)]) -> Result<(), String> {
    if actual.is_empty() {
        return Ok(());
    }
    let lines: Vec<String> =
        actual.iter().map(|(k, r, name, line)| format!("  {k}/{r}:{line} {name} -> Procedure")).collect();
    Err(format!(
        "Local Procedure-returning constructor functions/macros are forbidden outside ua-store (reuse ua_store::org::tenant_part or move to ua-store):\n{}",
        lines.join("\n")
    ))
}

