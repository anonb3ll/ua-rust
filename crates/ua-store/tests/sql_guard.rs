#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum HelperVis {
    Private,
    PubSuper,
    PubCrate,
    Pub,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum HelperKind {
    Fn,
    Method,
    Closure,
    Macro,
}

#[derive(Debug, Clone, PartialEq, Eq)]
struct DetectedHelper {
    name: String,
    vis: HelperVis,
    kind: HelperKind,
    is_pub: bool,
    line: usize,
    sql_param_indices: Vec<usize>,
}

fn vis_of(vis: &Visibility, in_pub_trait_impl: bool) -> (HelperVis, bool) {
    if in_pub_trait_impl {
        return (HelperVis::Pub, true);
    }
    match vis {
        Visibility::Public(_) => (HelperVis::Pub, true),
        Visibility::Restricted(r) => {
            if r.path.is_ident("crate") {
                (HelperVis::PubCrate, false)
            } else {
                (HelperVis::PubSuper, false)
            }
        }
        Visibility::Inherited => (HelperVis::Private, false),
    }
}

/// Extract `{ident}` / `{ident:...}` capture names from a Rust format string literal.
fn format_captures(fmt: &str) -> Vec<String> {
    let b = fmt.as_bytes();
    let mut out = Vec::new();
    let mut i = 0;
    while i < b.len() {
        if b[i] == b'{' {
            if b.get(i + 1) == Some(&b'{') {
                i += 2;
                continue;
            }
            i += 1;
            let start = i;
            while i < b.len() && (b[i].is_ascii_alphanumeric() || b[i] == b'_') {
                i += 1;
            }
            if i > start
                && (b[start].is_ascii_alphabetic() || b[start] == b'_')
                && matches!(b.get(i), Some(b'}' | b':'))
            {
                out.push(fmt[start..i].to_string());
            }
        } else {
            i += 1;
        }
    }
    out
}

fn quote_brackets(inner: TokenStream) -> TokenStream {
    TokenStream::from(TokenTree::Group(proc_macro2::Group::new(Delimiter::Bracket, inner)))
}

/// Does `tokens` inside a macro invocation (`format!`, `write!`, `vec!`, etc.)
/// use any identifier in `tainted` as string/data content (including `{ident}`
/// format string captures)?
fn macro_tokens_use_tainted(
    mac: &syn::Macro,
    tainted: &BTreeSet<String>,
    ret_taint: &LocalReturnTaint,
) -> bool {
    let parsed = macro_parse(mac);
    if let Some(expr) = &parsed.vec_expr {
        return expr_uses_tainted(expr, tainted, ret_taint);
    }
    if parsed.fmt_captures.iter().any(|cap| tainted.contains(cap)) {
        return true;
    }
    if let Some(exprs) = &parsed.args {
        return exprs.iter().any(|e| expr_uses_tainted(e, tainted, ret_taint));
    }
    // Fallback token scan: match any ident not preceded by `.` or `:`.
    tokens_use_tainted_raw(mac.tokens.clone(), tainted)
}

fn tokens_use_tainted_raw(stream: TokenStream, tainted: &BTreeSet<String>) -> bool {
    let tts: Vec<TokenTree> = stream.into_iter().collect();
    for (i, tt) in tts.iter().enumerate() {
        match tt {
            TokenTree::Ident(id) if tainted.contains(&id.to_string()) => {
                let prev_member =
                    i > 0 && matches!(&tts[i - 1], TokenTree::Punct(p) if matches!(p.as_char(), '.' | ':'));
                if !prev_member {
                    return true;
                }
            }
            TokenTree::Group(g) if tokens_use_tainted_raw(g.stream(), tainted) => return true,
            _ => {}
        }
    }
    false
}

/// Summary of which parameters of a local function/method flow into which
/// return value slot (slot `0` for non-tuple returns, or `0..N` for tuple
/// returns `(e0, e1, ...)`) and, when the return value is a struct literal or
/// `self`-returning builder chain, which struct fields are tainted by which
/// parameters. Parameter index `0` for a method with `self` is `self`;
/// subsequent parameters are `1..`. For free/associated functions, parameter
/// indices are `0..`.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
struct StructReturnSummary {
    /// True when the method returns `self` (directly or via a `self`-returning
    /// builder chain), preserving whatever field taints the receiver already had.
    passthrough_self: bool,
    /// Map from struct field name -> parameter indices that taint that field.
    fields: BTreeMap<String, BTreeSet<usize>>,
}

/// `(fn_or_method_name, has_self, explicit_arity)`.
type SummaryKey = (String, bool, usize);

#[derive(Debug, Default, Clone)]
struct LocalReturnTaint {
    /// Map from return tuple slot index to set of parameter indices that flow
    /// into that slot.
    slots: BTreeMap<SummaryKey, BTreeMap<usize, BTreeSet<usize>>>,
    /// Per-field struct return summary, populated only when every callable
    /// with that key returns a field-tracked struct value.
    structs: BTreeMap<SummaryKey, StructReturnSummary>,
    /// Crate-wide summaries consulted for keys this layer does not define.
    base: Option<Rc<LocalReturnTaint>>,
    /// Keys defined by this layer; they shadow `base` even when absent here.
    local_keys: Rc<BTreeSet<SummaryKey>>,
}

impl PartialEq for LocalReturnTaint {
    /// Fixed-point check: only this layer changes between iterations.
    fn eq(&self, other: &Self) -> bool {
        self.slots == other.slots && self.structs == other.structs
    }
}

impl LocalReturnTaint {
    fn layered(base: Option<Rc<LocalReturnTaint>>, local_keys: Rc<BTreeSet<SummaryKey>>) -> Self {
        Self { slots: BTreeMap::new(), structs: BTreeMap::new(), base, local_keys }
    }

    fn slot_map(&self, key: &SummaryKey) -> Option<&BTreeMap<usize, BTreeSet<usize>>> {
        if let Some(m) = self.slots.get(key) {
            return Some(m);
        }
        if self.local_keys.contains(key) {
            return None;
        }
        self.base.as_deref()?.slot_map(key)
    }

    fn struct_summary(&self, key: &SummaryKey) -> Option<&StructReturnSummary> {
        if let Some(s) = self.structs.get(key) {
            return Some(s);
        }
        if self.local_keys.contains(key) {
            return None;
        }
        self.base.as_deref()?.struct_summary(key)
    }

    fn known(&self, name: &str, has_self: bool, explicit_arity: usize) -> bool {
        self.slot_map(&(name.to_string(), has_self, explicit_arity)).is_some()
    }

    fn slot_tainted_by_args(
        &self,
        name: &str,
        has_self: bool,
        explicit_arity: usize,
        slot: usize,
        receiver_tainted: bool,
        args_tainted: &[bool],
    ) -> Option<bool> {
        let slot_map = self.slot_map(&(name.to_string(), has_self, explicit_arity))?;
        let Some(param_idxs) = slot_map.get(&slot) else {
            return Some(false);
        };
        if has_self {
            if receiver_tainted && param_idxs.contains(&0) {
                return Some(true);
            }
            for (i, &t) in args_tainted.iter().enumerate() {
                if t && param_idxs.contains(&(i + 1)) {
                    return Some(true);
                }
            }
        } else {
            for (i, &t) in args_tainted.iter().enumerate() {
                if t && param_idxs.contains(&i) {
                    return Some(true);
                }
            }
        }
        Some(false)
    }

    fn any_slot_tainted_by_args(
        &self,
        name: &str,
        has_self: bool,
        explicit_arity: usize,
        receiver_tainted: bool,
        args_tainted: &[bool],
    ) -> Option<bool> {
        let slot_map = self.slot_map(&(name.to_string(), has_self, explicit_arity))?;
        for &slot in slot_map.keys() {
            if self.slot_tainted_by_args(name, has_self, explicit_arity, slot, receiver_tainted, args_tainted)
                == Some(true)
            {
                return Some(true);
            }
        }
        Some(false)
    }
}

fn member_name(member: &syn::Member) -> String {
    match member {
        syn::Member::Named(id) => id.to_string(),
        syn::Member::Unnamed(idx) => idx.index.to_string(),
    }
}

fn is_diverging_expr(expr: &Expr) -> bool {
    match unwrap_parens(expr) {
        Expr::Return(_) | Expr::Break(_) | Expr::Continue(_) => true,
        Expr::Block(b) => match b.block.stmts.last() {
            Some(Stmt::Expr(e, _)) => is_diverging_expr(e),
            Some(Stmt::Macro(m)) => m.mac.path.segments.last().is_some_and(|s| {
                matches!(s.ident.to_string().as_str(), "panic" | "unreachable" | "todo" | "unimplemented")
            }),
            _ => false,
        },
        Expr::Macro(m) => m.mac.path.segments.last().is_some_and(|s| {
            matches!(s.ident.to_string().as_str(), "panic" | "unreachable" | "todo" | "unimplemented")
        }),
        _ => false,
    }
}

/// Tainted sub-paths of `var` (`sql`, `sets.#0`, ...): every tainted key
/// `var.<rest>` yields `<rest>`.
fn tainted_fields_of_var(var: &str, tainted: &BTreeSet<String>) -> BTreeSet<String> {
    let prefix = format!("{var}.");
    tainted
        .range(prefix.clone()..)
        .take_while(|k| k.starts_with(&prefix))
        .map(|k| k[prefix.len()..].to_string())
        .collect()
}

/// Is any sub-path of `key` (`key.<field>`, `key.#<slot>`) tainted?
fn has_tainted_under(tainted: &BTreeSet<String>, key: &str) -> bool {
    // Keys are identifier paths (`a`, `a.b`, `a.#0`): no key char sorts below
    // `.`, so every `key.<rest>` entry directly follows `key` in order.
    use std::ops::Bound;
    tainted
        .range::<str, _>((Bound::Excluded(key), Bound::Unbounded))
        .next()
        .is_some_and(|k| k.len() > key.len() && k.starts_with(key) && k.as_bytes()[key.len()] == b'.')
}

/// Is a strict ancestor place of `key` (`a` or `a.b` for `a.b.c`) tainted as a whole?
fn ancestor_tainted(tainted: &BTreeSet<String>, key: &str) -> bool {
    let mut k = key;
    while let Some(pos) = k.rfind('.') {
        k = &k[..pos];
        if tainted.contains(k) {
            return true;
        }
    }
    false
}

/// Whole-value use of a place: tainted when the place itself, any ancestor, or
/// any of its sub-paths is tainted (a struct whose `sql` field is tainted is
/// tainted when used whole, e.g. `w.render()` or `format!("{w}")`).
fn place_tainted(tainted: &BTreeSet<String>, key: &str) -> bool {
    tainted.contains(key) || ancestor_tainted(tainted, key) || has_tainted_under(tainted, key)
}

/// Does a caller's tainted sub-path `a` overlap a callee's SQL-reaching sub-path `f`?
fn field_paths_overlap(a: &str, f: &str) -> bool {
    a == f
        || (a.len() > f.len() && a.starts_with(f) && a.as_bytes()[f.len()] == b'.')
        || (f.len() > a.len() && f.starts_with(a) && f.as_bytes()[a.len()] == b'.')
}

/// Evaluate an expression to the exact set of tainted struct fields when it is
/// known to produce a field-tracked struct (struct literal, field-tracked
/// variable, or call/method-call with a `StructReturnSummary`). Returns `None`
/// if the expression is not field-tracked or is whole-tainted.
fn eval_struct_expr_taint(
    expr: &Expr,
    tainted: &BTreeSet<String>,
    ret_taint: &LocalReturnTaint,
) -> Option<BTreeSet<String>> {
    let e = unwrap_result_wrapper(unwrap_try_and_parens(expr));
    match e {
        Expr::Reference(r) => eval_struct_expr_taint(&r.expr, tainted, ret_taint),
        Expr::Struct(es) => {
            let mut out = if let Some(rest) = &es.rest {
                if let Some(base) = eval_struct_expr_taint(rest, tainted, ret_taint) {
                    base
                } else if expr_uses_tainted(rest, tainted, ret_taint) {
                    return None;
                } else {
                    BTreeSet::new()
                }
            } else {
                BTreeSet::new()
            };
            for f in &es.fields {
                let fname = member_name(&f.member);
                let sub = format!("{fname}.");
                out.retain(|k| !k.starts_with(&sub));
                if expr_uses_tainted(&f.expr, tainted, ret_taint) {
                    out.insert(fname);
                } else {
                    out.remove(&fname);
                }
            }
            Some(out)
        }
        Expr::Path(ep) => {
            if ep.qself.is_none() && ep.path.segments.len() == 1 {
                let id = ep.path.segments[0].ident.to_string();
                if tainted.contains(&id) {
                    return None;
                }
                let fields = tainted_fields_of_var(&id, tainted);
                if !fields.is_empty() {
                    return Some(fields);
                }
            }
            None
        }
        Expr::Call(c) => {
            if let Expr::Path(ep) = unwrap_parens(&c.func)
                && ep.qself.is_none()
                && let Some(last) = ep.path.segments.last()
            {
                let name = last.ident.to_string();
                let key = (name, false, c.args.len());
                if let Some(summary) = ret_taint.struct_summary(&key) {
                    let args_t: Vec<bool> =
                        c.args.iter().map(|a| expr_uses_tainted(a, tainted, ret_taint)).collect();
                    let mut out = BTreeSet::new();
                    for (field, param_idxs) in &summary.fields {
                        if args_t.iter().enumerate().any(|(i, &t)| t && param_idxs.contains(&i)) {
                            out.insert(field.clone());
                        }
                    }
                    return Some(out);
                }
            }
            None
        }
        Expr::MethodCall(mc) => {
            let name = mc.method.to_string();
            let key = (name, true, mc.args.len());
            if let Some(summary) = ret_taint.struct_summary(&key) {
                let args_t: Vec<bool> =
                    mc.args.iter().map(|a| expr_uses_tainted(a, tainted, ret_taint)).collect();
                // Evaluate the receiver once: builder chains (`tool(..).approval(..).gated(..)`)
                // would otherwise re-evaluate every link twice per level (2^chain length).
                let recv_fields = eval_struct_expr_taint(&mc.receiver, tainted, ret_taint);
                let recv_whole = expr_uses_tainted(&mc.receiver, tainted, ret_taint);
                let mut out = BTreeSet::new();
                if summary.passthrough_self {
                    if let Some(fields) = &recv_fields {
                        out.extend(fields.iter().cloned());
                    } else if recv_whole {
                        return None;
                    }
                }
                let recv_any_tainted = recv_whole || recv_fields.as_ref().is_some_and(|fs| !fs.is_empty());
                for (field, param_idxs) in &summary.fields {
                    let hit_self = recv_any_tainted && param_idxs.contains(&0);
                    let hit_arg = args_t.iter().enumerate().any(|(i, &t)| t && param_idxs.contains(&(i + 1)));
                    if hit_self || hit_arg {
                        out.insert(field.clone());
                    }
                }
                return Some(out);
            }
            None
        }
        Expr::Block(b) => match b.block.stmts.last() {
            Some(Stmt::Expr(tail, None)) => eval_struct_expr_taint(tail, tainted, ret_taint),
            _ => None,
        },
        Expr::If(ei) => {
            let mut then_tainted = tainted.clone();
            if let Expr::Let(el) = &*ei.cond {
                let cond_t = expr_uses_tainted(&el.expr, tainted, ret_taint);
                let mut vars = Vec::new();
                collect_pat_idents(&el.pat, &mut vars);
                if cond_t {
                    then_tainted.extend(vars);
                } else {
                    for v in vars {
                        then_tainted.remove(&v);
                    }
                }
            }
            let then_res = match ei.then_branch.stmts.last() {
                Some(Stmt::Expr(tail, None)) if is_diverging_expr(tail) => Some(BTreeSet::new()),
                Some(Stmt::Expr(tail, None)) => eval_struct_expr_taint(tail, &then_tainted, ret_taint),
                _ => None,
            }?;
            let else_res = match &ei.else_branch {
                Some((_, eb)) if is_diverging_expr(eb) => Some(BTreeSet::new()),
                Some((_, eb)) => eval_struct_expr_taint(eb, tainted, ret_taint),
                None => None,
            }?;
            let mut out = then_res;
            out.extend(else_res);
            Some(out)
        }
        Expr::Match(em) => {
            if em.arms.is_empty() {
                return None;
            }
            let scrut_t = expr_uses_tainted(&em.expr, tainted, ret_taint);
            let mut out = BTreeSet::new();
            let mut any_non_div = false;
            for arm in &em.arms {
                if is_diverging_expr(&arm.body) {
                    continue;
                }
                any_non_div = true;
                let mut arm_tainted = tainted.clone();
                let mut vars = Vec::new();
                collect_pat_idents(&arm.pat, &mut vars);
                if scrut_t {
                    arm_tainted.extend(vars);
                } else {
                    for v in vars {
                        arm_tainted.remove(&v);
                    }
                }
                let arm_fields = eval_struct_expr_taint(&arm.body, &arm_tainted, ret_taint)?;
                out.extend(arm_fields);
            }
            any_non_div.then_some(out)
        }
        _ => None,
    }
}

fn is_struct_shaped_ret(expr: &Expr, has_self: bool, ret_taint: &LocalReturnTaint) -> bool {
    let e = unwrap_result_wrapper(unwrap_try_and_parens(expr));
    if is_diverging_expr(e) {
        return true;
    }
    match e {
        Expr::Struct(_) => true,
        Expr::Path(ep) => has_self && ep.qself.is_none() && ep.path.is_ident("self"),
        Expr::Call(c) => {
            if let Expr::Path(ep) = unwrap_parens(&c.func)
                && ep.qself.is_none()
                && let Some(last) = ep.path.segments.last()
            {
                ret_taint.struct_summary(&(last.ident.to_string(), false, c.args.len())).is_some()
            } else {
                false
            }
        }
        Expr::MethodCall(mc) => {
            ret_taint.struct_summary(&(mc.method.to_string(), true, mc.args.len())).is_some()
        }
        Expr::Block(b) => match b.block.stmts.last() {
            Some(Stmt::Expr(tail, None)) => is_struct_shaped_ret(tail, has_self, ret_taint),
            _ => false,
        },
        Expr::If(ei) => {
            let then_ok = match ei.then_branch.stmts.last() {
                Some(Stmt::Expr(tail, None)) => is_struct_shaped_ret(tail, has_self, ret_taint),
                _ => false,
            };
            let else_ok = match &ei.else_branch {
                Some((_, eb)) => is_struct_shaped_ret(eb, has_self, ret_taint),
                None => false,
            };
            then_ok && else_ok
        }
        Expr::Match(em) => {
            !em.arms.is_empty() && em.arms.iter().all(|a| is_struct_shaped_ret(&a.body, has_self, ret_taint))
        }
        _ => false,
    }
}

fn ret_passes_self_through(expr: &Expr, ret_taint: &LocalReturnTaint) -> bool {
    let e = unwrap_result_wrapper(unwrap_try_and_parens(expr));
    match e {
        Expr::Path(ep) => ep.qself.is_none() && ep.path.is_ident("self"),
        Expr::MethodCall(mc) => {
            let key = (mc.method.to_string(), true, mc.args.len());
            ret_taint.struct_summary(&key).is_some_and(|s| s.passthrough_self)
                && ret_passes_self_through(&mc.receiver, ret_taint)
        }
        Expr::Block(b) => match b.block.stmts.last() {
            Some(Stmt::Expr(tail, None)) => ret_passes_self_through(tail, ret_taint),
            _ => false,
        },
        Expr::If(ei) => {
            let then_p = match ei.then_branch.stmts.last() {
                Some(Stmt::Expr(tail, None)) => ret_passes_self_through(tail, ret_taint),
                _ => false,
            };
            let else_p =
                ei.else_branch.as_ref().is_some_and(|(_, eb)| ret_passes_self_through(eb, ret_taint));
            then_p || else_p
        }
        Expr::Match(em) => em.arms.iter().any(|a| ret_passes_self_through(&a.body, ret_taint)),
        _ => false,
    }
}

/// Whether `expr` is an integer literal or ALL_CAPS constant path (used to
/// recognize bounded integer limits like `n.min(MAX_LIMIT)`).
fn is_int_or_const_bound(expr: &Expr) -> bool {
    match unwrap_parens(expr) {
        Expr::Lit(l) => matches!(l.lit, syn::Lit::Int(_)),
        Expr::Path(ep) => ep.path.segments.last().is_some_and(|s| {
            let id = s.ident.to_string();
            !id.is_empty() && id.bytes().all(|b| b.is_ascii_uppercase() || b.is_ascii_digit() || b == b'_')
        }),
        _ => false,
    }
}

/// Does `expr` use any identifier in `tainted` as SQL/data content (directly,
/// via field access `q.0` / `q.text`, via method call `q.to_string()`, or via
/// `format!("{q}")`), while ignoring pure control-flow conditions (`if <cond>`),
/// boolean comparisons (`==`, `!=`, `<`, ...), bounded integer clamping
/// (`.clamp(...)`, `.min(MAX_LIMIT)`), and length/presence queries (`.len()`,
/// `.is_empty()`, `.is_some()`, `.is_none()`)?
fn expr_uses_tainted(expr: &Expr, tainted: &BTreeSet<String>, ret_taint: &LocalReturnTaint) -> bool {
    match expr {
        Expr::Path(ep) => {
            ep.qself.is_none()
                && ep.path.segments.len() == 1
                && place_tainted(tainted, &ep.path.segments[0].ident.to_string())
        }
        Expr::Field(ExprField { base, .. }) => match place_key_of_expr(expr) {
            // `x.f` is tainted by `x`, `x.f`, or anything under `x.f`, but not
            // by a sibling field `x.g`.
            Some(key) => place_tainted(tainted, &key),
            None => expr_uses_tainted(base, tainted, ret_taint),
        },
        Expr::MethodCall(mc) => {
            let m = mc.method.to_string();
            if matches!(m.as_str(), "len" | "is_empty" | "is_some" | "is_none" | "count" | "capacity")
                && mc.args.is_empty()
            {
                return false;
            }
            if m == "clamp" || (m == "min" && mc.args.len() == 1 && is_int_or_const_bound(&mc.args[0])) {
                return false;
            }
            if let Some(res) = tuple_projection_taint(mc, tainted, ret_taint) {
                return res;
            }
            let recv_t = expr_uses_tainted(&mc.receiver, tainted, ret_taint);
            let args_t: Vec<bool> =
                mc.args.iter().map(|a| expr_uses_tainted(a, tainted, ret_taint)).collect();
            if let Some(res) = ret_taint.any_slot_tainted_by_args(&m, true, mc.args.len(), recv_t, &args_t) {
                return res;
            }
            recv_t || args_t.into_iter().any(|x| x)
        }
        Expr::Binary(b) => {
            if matches!(
                b.op,
                BinOp::Eq(_)
                    | BinOp::Ne(_)
                    | BinOp::Lt(_)
                    | BinOp::Le(_)
                    | BinOp::Gt(_)
                    | BinOp::Ge(_)
                    | BinOp::And(_)
                    | BinOp::Or(_)
            ) {
                return false;
            }
            expr_uses_tainted(&b.left, tainted, ret_taint) || expr_uses_tainted(&b.right, tainted, ret_taint)
        }
        Expr::If(ExprIf { cond, then_branch, else_branch, .. }) => {
            let mut branch_tainted = tainted.clone();
            if let Expr::Let(el) = &**cond
                && expr_uses_tainted(&el.expr, tainted, ret_taint)
            {
                let mut bound = Vec::new();
                collect_pat_idents(&el.pat, &mut bound);
                branch_tainted.extend(bound);
            }
            block_uses_tainted(then_branch, &branch_tainted, ret_taint)
                || else_branch.as_ref().is_some_and(|(_, e)| expr_uses_tainted(e, tainted, ret_taint))
        }
        Expr::Match(ExprMatch { expr: scrutinee, arms, .. }) => {
            let scrutinee_tainted = expr_uses_tainted(scrutinee, tainted, ret_taint);
            arms.iter().any(|arm| {
                let mut arm_tainted = tainted.clone();
                let mut bound = Vec::new();
                collect_pat_idents(&arm.pat, &mut bound);
                if scrutinee_tainted {
                    arm_tainted.extend(bound);
                } else {
                    for b in bound {
                        arm_tainted.remove(&b);
                    }
                }
                expr_uses_tainted(&arm.body, &arm_tainted, ret_taint)
            })
        }
        Expr::Macro(em) => macro_tokens_use_tainted(&em.mac, tainted, ret_taint),
        Expr::Call(c) => {
            if let Expr::Path(ep) = unwrap_parens(&c.func)
                && ep.qself.is_none()
                && ep.path.segments.len() == 1
            {
                let name = ep.path.segments[0].ident.to_string();
                if ret_taint.known(&name, false, c.args.len()) {
                    let args_t: Vec<bool> =
                        c.args.iter().map(|a| expr_uses_tainted(a, tainted, ret_taint)).collect();
                    if let Some(res) =
                        ret_taint.any_slot_tainted_by_args(&name, false, c.args.len(), false, &args_t)
                    {
                        return res;
                    }
                }
            }
            expr_uses_tainted(&c.func, tainted, ret_taint)
                || c.args.iter().any(|a| expr_uses_tainted(a, tainted, ret_taint))
        }
        Expr::Reference(r) => expr_uses_tainted(&r.expr, tainted, ret_taint),
        Expr::Unary(u) => expr_uses_tainted(&u.expr, tainted, ret_taint),
        Expr::Try(t) => expr_uses_tainted(&t.expr, tainted, ret_taint),
        Expr::Cast(c) => expr_uses_tainted(&c.expr, tainted, ret_taint),
        Expr::Paren(p) => expr_uses_tainted(&p.expr, tainted, ret_taint),
        Expr::Group(g) => expr_uses_tainted(&g.expr, tainted, ret_taint),
        Expr::Index(idx) => {
            expr_uses_tainted(&idx.expr, tainted, ret_taint)
                || expr_uses_tainted(&idx.index, tainted, ret_taint)
        }
        Expr::Block(b) => block_uses_tainted(&b.block, tainted, ret_taint),
        Expr::Array(a) => a.elems.iter().any(|e| expr_uses_tainted(e, tainted, ret_taint)),
        Expr::Tuple(t) => t.elems.iter().any(|e| expr_uses_tainted(e, tainted, ret_taint)),
        Expr::Repeat(r) => expr_uses_tainted(&r.expr, tainted, ret_taint),
        Expr::Return(r) => r.expr.as_ref().is_some_and(|e| expr_uses_tainted(e, tainted, ret_taint)),
        Expr::Await(a) => expr_uses_tainted(&a.base, tainted, ret_taint),
        Expr::Unsafe(u) => block_uses_tainted(&u.block, tainted, ret_taint),
        Expr::Async(a) => block_uses_tainted(&a.block, tainted, ret_taint),
        Expr::Closure(c) => {
            let mut inner_tainted = tainted.clone();
            for pat in &c.inputs {
                let mut shadowed = Vec::new();
                collect_pat_idents(pat, &mut shadowed);
                for s in shadowed {
                    inner_tainted.remove(&s);
                }
            }
            expr_uses_tainted(&c.body, &inner_tainted, ret_taint)
        }
        Expr::Struct(ExprStruct { fields, rest, .. }) => {
            fields.iter().any(|f| expr_uses_tainted(&f.expr, tainted, ret_taint))
                || rest.as_ref().is_some_and(|r| expr_uses_tainted(r, tainted, ret_taint))
        }
        Expr::Lit(_) => false,
        _ => false,
    }
}

/// Iterator adapters that keep each item as it is.
const ITEM_PRESERVING_ADAPTERS: &[&str] = &["iter", "into_iter", "iter_mut", "cloned", "copied", "rev"];

/// Strip item-preserving iterator adapters (`fields.iter().cloned()` -> `fields`).
fn strip_item_adapters(mut expr: &Expr) -> &Expr {
    loop {
        match unwrap_ref_or_cast(expr) {
            Expr::MethodCall(mc)
                if mc.args.is_empty()
                    && ITEM_PRESERVING_ADAPTERS.contains(&mc.method.to_string().as_str()) =>
            {
                expr = &mc.receiver;
            }
            other => return other,
        }
    }
}

fn unwrap_pat_ref_type_paren(mut pat: &Pat) -> &Pat {
    loop {
        match pat {
            Pat::Type(pt) => pat = &pt.pat,
            Pat::Paren(pp) => pat = &pp.pat,
            Pat::Reference(pr) => pat = &pr.pat,
            _ => return pat,
        }
    }
}

/// `fields.iter().map(|(col, _)| ..)` over a place with per-slot taint
/// (`fields.#<slot>`): bind each tuple element of the closure pattern to its
/// slot's taint and evaluate the closure body. `None` when the shape does not
/// apply, so the caller falls back to whole-value taint.
fn tuple_projection_taint(
    mc: &ExprMethodCall,
    tainted: &BTreeSet<String>,
    ret_taint: &LocalReturnTaint,
) -> Option<bool> {
    let m = mc.method.to_string();
    if !matches!(m.as_str(), "map" | "filter_map" | "flat_map" | "for_each" | "find_map" | "map_while")
        || mc.args.len() != 1
    {
        return None;
    }
    let Expr::Closure(cl) = unwrap_parens(&mc.args[0]) else { return None };
    let Pat::Tuple(pt) = unwrap_pat_ref_type_paren(cl.inputs.first()?) else { return None };
    let place = place_key_of_expr(strip_item_adapters(&mc.receiver))?;
    if tainted.contains(&place) || ancestor_tainted(tainted, &place) {
        return None;
    }
    let slots = tuple_slot_taint(tainted, &place)?;
    let mut inner = tainted.clone();
    for input in &cl.inputs {
        let mut shadowed = Vec::new();
        collect_pat_idents(input, &mut shadowed);
        for v in shadowed {
            inner.remove(&v);
        }
    }
    for (slot, elem) in pt.elems.iter().enumerate() {
        if slots.contains(&slot) {
            let mut vars = Vec::new();
            collect_pat_idents(elem, &mut vars);
            inner.extend(vars);
        }
    }
    Some(expr_uses_tainted(&cl.body, &inner, ret_taint))
}

fn block_uses_tainted(block: &syn::Block, tainted: &BTreeSet<String>, ret_taint: &LocalReturnTaint) -> bool {
    block.stmts.iter().any(|s| match s {
        Stmt::Expr(e, _) => expr_uses_tainted(e, tainted, ret_taint),
        Stmt::Local(l) => l.init.as_ref().is_some_and(|i| expr_uses_tainted(&i.expr, tainted, ret_taint)),
        Stmt::Macro(m) => macro_tokens_use_tainted(&m.mac, tainted, ret_taint),
        Stmt::Item(_) => false,
    })
}

fn unwrap_pat_type_and_parens(mut pat: &Pat) -> &Pat {
    loop {
        match pat {
            Pat::Type(pt) => pat = &pt.pat,
            Pat::Paren(pp) => pat = &pp.pat,
            _ => return pat,
        }
    }
}

/// Evaluate whether tuple slot `slot` of a tuple-valued expression (direct tuple
/// literal, `Ok(...)`/`Some(...)`, block tail, `if`/`else`, or `match` arms with
/// optional diverging arms) uses any identifier in `tainted`. Returns `None` if
/// any non-diverging branch is not a direct tuple literal (caller falls back to
/// whole-expression taint).
fn eval_tuple_slot_tainted(
    expr: &Expr,
    slot: usize,
    tainted: &BTreeSet<String>,
    ret_taint: &LocalReturnTaint,
) -> Option<bool> {
    let e = unwrap_result_wrapper(unwrap_try_and_parens(expr));
    if is_diverging_expr(e) {
        return Some(false);
    }
    match e {
        Expr::Tuple(t) => {
            Some(t.elems.iter().nth(slot).is_some_and(|item| expr_uses_tainted(item, tainted, ret_taint)))
        }
        Expr::Block(b) => match b.block.stmts.last() {
            Some(Stmt::Expr(tail, None)) => eval_tuple_slot_tainted(tail, slot, tainted, ret_taint),
            _ => None,
        },
        Expr::If(ei) => {
            let mut then_tainted = tainted.clone();
            if let Expr::Let(el) = &*ei.cond {
                let cond_t = expr_uses_tainted(&el.expr, tainted, ret_taint);
                let mut vars = Vec::new();
                collect_pat_idents(&el.pat, &mut vars);
                if cond_t {
                    then_tainted.extend(vars);
                } else {
                    for v in vars {
                        then_tainted.remove(&v);
                    }
                }
            }
            let then_t = match ei.then_branch.stmts.last() {
                Some(Stmt::Expr(tail, None)) => eval_tuple_slot_tainted(tail, slot, &then_tainted, ret_taint),
                _ => None,
            }?;
            let else_t = match &ei.else_branch {
                Some((_, eb)) => eval_tuple_slot_tainted(eb, slot, tainted, ret_taint),
                None => None,
            }?;
            Some(then_t || else_t)
        }
        Expr::Match(em) => {
            if em.arms.is_empty() {
                return None;
            }
            let scrut_t = expr_uses_tainted(&em.expr, tainted, ret_taint);
            let mut any_non_div = false;
            let mut hit = false;
            for arm in &em.arms {
                if is_diverging_expr(&arm.body) {
                    continue;
                }
                any_non_div = true;
                let mut arm_tainted = tainted.clone();
                let mut vars = Vec::new();
                collect_pat_idents(&arm.pat, &mut vars);
                if scrut_t {
                    arm_tainted.extend(vars);
                } else {
                    for v in vars {
                        arm_tainted.remove(&v);
                    }
                }
                hit |= eval_tuple_slot_tainted(&arm.body, slot, &arm_tainted, ret_taint)?;
            }
            any_non_div.then_some(hit)
        }
        _ => None,
    }
}

/// Arity of the first tuple literal a tuple-valued expression resolves to
/// (through `Ok`/`Some`, `?`, block tails, `if`/`else`, and `match` arms).
fn tuple_ret_arity(expr: &Expr) -> Option<usize> {
    match unwrap_result_wrapper(unwrap_try_and_parens(expr)) {
        Expr::Tuple(t) => Some(t.elems.len()),
        Expr::Block(b) => match b.block.stmts.last() {
            Some(Stmt::Expr(tail, None)) => tuple_ret_arity(tail),
            _ => None,
        },
        Expr::If(ei) => {
            let then_a = match ei.then_branch.stmts.last() {
                Some(Stmt::Expr(tail, None)) => tuple_ret_arity(tail),
                _ => None,
            };
            then_a.or_else(|| ei.else_branch.as_ref().and_then(|(_, eb)| tuple_ret_arity(eb)))
        }
        Expr::Match(em) => em.arms.iter().find_map(|a| tuple_ret_arity(&a.body)),
        _ => None,
    }
}

/// Per-slot taint of a tuple-valued return expression, or `None` when any
/// non-diverging branch is not a tuple literal (caller falls back to
/// whole-value taint).
fn eval_tuple_slots_tainted(
    expr: &Expr,
    tainted: &BTreeSet<String>,
    ret_taint: &LocalReturnTaint,
) -> Option<Vec<bool>> {
    let arity = tuple_ret_arity(expr)?;
    (0..arity).map(|slot| eval_tuple_slot_tainted(expr, slot, tainted, ret_taint)).collect()
}

/// Scoped bindings (`for`, `if let`, `while let`, `match` arms, closure
/// parameters) take their taint for the scope and give the name back its prior
/// state afterwards; `FlowProbe` checks SQL arguments, helper calls and returns
/// while those bindings are live.
///
/// Propagate taint through `let`, assignments, `push_str`/`push` (1-arg),
/// `write!`/`writeln!`, `if let`, `while let`, `match`, and `for` bindings,
/// using per-tuple-slot precision for tuple expressions, tuple-element vecs,
/// and local helpers, plus per-field struct precision for struct literals and
/// builder methods.
struct TaintPropagator<'a, 'h> {
    tainted: &'a mut BTreeSet<String>,
    ret_taint: &'a LocalReturnTaint,
    probe: Option<FlowProbe<'h>>,
}

/// In-flow checks made while taint propagates, so a SQL call, a helper call or
/// a `return` inside a scope (`for`, `if let`, `match` arm) sees the bindings
/// live at that point rather than the set left after the scope closed.
struct FlowProbe<'h> {
    /// Addresses of the SQL arguments of the body's direct SQL calls.
    sql_args: &'h HashSet<usize>,
    helpers: &'h KnownHelpers,
    aliases: BTreeMap<String, String>,
    hit: bool,
    /// Taint live at each `return <expr>`, keyed by the returned expression.
    returns: HashMap<usize, BTreeSet<String>>,
}

impl<'h> FlowProbe<'h> {
    fn new(sql_args: &'h HashSet<usize>, helpers: &'h KnownHelpers) -> Self {
        Self { sql_args, helpers, aliases: BTreeMap::new(), hit: false, returns: HashMap::new() }
    }
}

fn expr_addr(e: &Expr) -> usize {
    e as *const Expr as usize
}

impl TaintPropagator<'_, '_> {
    /// Bind scoped names (`for`/`if let`/`while let`/`match` arm patterns) to
    /// their taint, returning each name's prior state for `restore_scoped`.
    fn bind_scoped(&mut self, bindings: Vec<(String, bool)>) -> Vec<(String, bool)> {
        let mut saved = Vec::with_capacity(bindings.len());
        for (v, t) in bindings {
            saved.push((v.clone(), self.tainted.contains(&v)));
            if t {
                self.tainted.insert(v);
            } else {
                self.tainted.remove(&v);
            }
        }
        saved
    }

    fn restore_scoped(&mut self, saved: Vec<(String, bool)>) {
        for (v, was) in saved.into_iter().rev() {
            if was {
                self.tainted.insert(v);
            } else {
                self.tainted.remove(&v);
            }
        }
    }

    fn probe_macro(&mut self, mac: &syn::Macro) {
        if let Some(p) = self.probe.as_mut()
            && !p.hit
            && macro_hits_helper(mac, p.helpers, self.tainted, self.ret_taint)
        {
            p.hit = true;
        }
    }
}

fn pat_bindings(pat: &Pat, tainted: bool) -> Vec<(String, bool)> {
    let mut vars = Vec::new();
    collect_pat_idents(pat, &mut vars);
    vars.into_iter().map(|v| (v, tainted)).collect()
}

impl<'ast> Visit<'ast> for TaintPropagator<'_, '_> {
    fn visit_expr(&mut self, node: &'ast Expr) {
        if let Some(p) = self.probe.as_mut()
            && !p.hit
            && p.sql_args.contains(&expr_addr(node))
            && expr_uses_tainted(node, self.tainted, self.ret_taint)
        {
            p.hit = true;
        }
        visit::visit_expr(self, node);
    }

    fn visit_expr_call(&mut self, node: &'ast ExprCall) {
        if let Some(p) = self.probe.as_mut()
            && !p.hit
            && call_hits_helper(node, p.helpers, &p.aliases, self.tainted, self.ret_taint)
        {
            p.hit = true;
        }
        visit::visit_expr_call(self, node);
    }

    fn visit_expr_return(&mut self, node: &'ast syn::ExprReturn) {
        if let Some(p) = self.probe.as_mut()
            && let Some(e) = &node.expr
        {
            p.returns.entry(expr_addr(e)).or_default().extend(self.tainted.iter().cloned());
        }
        visit::visit_expr_return(self, node);
    }

    fn visit_item(&mut self, node: &'ast Item) {
        if item_has_cfg_test(node) {
            return;
        }
        visit::visit_item(self, node);
    }

    fn visit_local(&mut self, node: &'ast Local) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        if let Some(p) = self.probe.as_mut() {
            record_helper_alias(node, p.helpers, &mut p.aliases);
        }
        if let Some(init) = &node.init {
            let unwrapped_init = unwrap_try_and_parens(&init.expr);
            let pat = unwrap_pat_type_and_parens(&node.pat);

            // Per-tuple-slot precision for `let (a, b, ...)[: Ty] = ...`.
            if let Pat::Tuple(pt) = pat {
                let matched_slots = match unwrapped_init {
                    Expr::Call(c) => {
                        if let Expr::Path(ep) = unwrap_parens(&c.func)
                            && ep.qself.is_none()
                            && ep.path.segments.len() == 1
                        {
                            let name = ep.path.segments[0].ident.to_string();
                            if self.ret_taint.known(&name, false, c.args.len()) {
                                let args_t: Vec<bool> = c
                                    .args
                                    .iter()
                                    .map(|a| expr_uses_tainted(a, self.tainted, self.ret_taint))
                                    .collect();
                                Some((name, false, c.args.len(), false, args_t))
                            } else {
                                None
                            }
                        } else {
                            None
                        }
                    }
                    Expr::MethodCall(mc) => {
                        let name = mc.method.to_string();
                        if self.ret_taint.known(&name, true, mc.args.len()) {
                            let recv_t = expr_uses_tainted(&mc.receiver, self.tainted, self.ret_taint);
                            let args_t: Vec<bool> = mc
                                .args
                                .iter()
                                .map(|a| expr_uses_tainted(a, self.tainted, self.ret_taint))
                                .collect();
                            Some((name, true, mc.args.len(), recv_t, args_t))
                        } else {
                            None
                        }
                    }
                    _ => None,
                };
                if let Some((name, has_self, arity, recv_t, args_t)) = matched_slots {
                    for (slot, elem_pat) in pt.elems.iter().enumerate() {
                        if self.ret_taint.slot_tainted_by_args(&name, has_self, arity, slot, recv_t, &args_t)
                            == Some(true)
                        {
                            let mut vars = Vec::new();
                            collect_pat_idents(elem_pat, &mut vars);
                            self.tainted.extend(vars);
                        }
                    }
                    visit::visit_local(self, node);
                    return;
                }
                let mut slot_results = Vec::with_capacity(pt.elems.len());
                let mut all_slots_resolved = true;
                for slot in 0..pt.elems.len() {
                    if let Some(t) =
                        eval_tuple_slot_tainted(unwrapped_init, slot, self.tainted, self.ret_taint)
                    {
                        slot_results.push(t);
                    } else {
                        all_slots_resolved = false;
                        break;
                    }
                }
                if all_slots_resolved {
                    for (elem_pat, is_t) in pt.elems.iter().zip(slot_results) {
                        if is_t {
                            let mut vars = Vec::new();
                            collect_pat_idents(elem_pat, &mut vars);
                            self.tainted.extend(vars);
                        }
                    }
                    visit::visit_local(self, node);
                    return;
                }
            }

            // Per-field struct precision for `let f = elig.filter()` or
            // `let edge = Edge::to(state).set("col", val)`.
            let mut bound_vars = Vec::new();
            collect_pat_idents(pat, &mut bound_vars);
            if bound_vars.len() == 1
                && let Some(tainted_fields) = eval_struct_expr_taint(&init.expr, self.tainted, self.ret_taint)
            {
                let var = &bound_vars[0];
                for field in tainted_fields {
                    self.tainted.insert(format!("{var}.{field}"));
                }
                visit::visit_local(self, node);
                return;
            }

            if expr_uses_tainted(&init.expr, self.tainted, self.ret_taint) {
                self.tainted.extend(bound_vars);
            }
        }
        visit::visit_local(self, node);
    }

    fn visit_expr_assign(&mut self, node: &'ast syn::ExprAssign) {
        if let Some(place) = place_key_of_expr(&node.left) {
            if let Some(tainted_fields) = eval_struct_expr_taint(&node.right, self.tainted, self.ret_taint) {
                for field in tainted_fields {
                    self.tainted.insert(format!("{place}.{field}"));
                }
            } else if expr_uses_tainted(&node.right, self.tainted, self.ret_taint) {
                self.tainted.insert(place);
            }
        }
        visit::visit_expr_assign(self, node);
    }

    fn visit_expr_method_call(&mut self, node: &'ast ExprMethodCall) {
        if let Some(p) = self.probe.as_mut()
            && !p.hit
            && method_call_hits_helper(node, p.helpers, self.tainted, self.ret_taint)
        {
            p.hit = true;
        }
        let m = node.method.to_string();
        if matches!(m.as_str(), "push_str" | "push")
            && node.args.len() == 1
            && let Some(place) = place_key_of_expr(&node.receiver)
        {
            if m == "push"
                && let Expr::Tuple(t) = unwrap_parens(&node.args[0])
            {
                // Track per-slot taint for `Vec<(A, B)>` pushes like `fields.push(("col", val))`
                // as sub-paths `fields.#<slot>`: destructuring `for (col, val) in &fields`
                // keeps the slots apart, while any whole use of `fields` is tainted.
                for (slot, elem) in t.elems.iter().enumerate() {
                    if expr_uses_tainted(elem, self.tainted, self.ret_taint) {
                        self.tainted.insert(format!("{place}.#{slot}"));
                    }
                }
            } else if expr_uses_tainted(&node.args[0], self.tainted, self.ret_taint) {
                self.tainted.insert(place);
            }
        }
        visit::visit_expr_method_call(self, node);
    }

    fn visit_macro(&mut self, node: &'ast syn::Macro) {
        self.propagate_write_macro(node);
        self.probe_macro(node);
        visit_macro_with(node, self);
    }

    fn visit_stmt(&mut self, node: &'ast Stmt) {
        if stmt_has_cfg_test(node) {
            return;
        }
        visit::visit_stmt(self, node);
    }

    fn visit_expr_if(&mut self, node: &'ast ExprIf) {
        self.visit_expr(&node.cond);
        let saved = if let Expr::Let(el) = &*node.cond {
            let cond_t = expr_uses_tainted(&el.expr, self.tainted, self.ret_taint);
            self.bind_scoped(pat_bindings(&el.pat, cond_t))
        } else {
            Vec::new()
        };
        self.visit_block(&node.then_branch);
        self.restore_scoped(saved);
        if let Some((_, eb)) = &node.else_branch {
            self.visit_expr(eb);
        }
    }

    fn visit_expr_while(&mut self, node: &'ast ExprWhile) {
        self.visit_expr(&node.cond);
        let saved = if let Expr::Let(el) = &*node.cond {
            let cond_t = expr_uses_tainted(&el.expr, self.tainted, self.ret_taint);
            self.bind_scoped(pat_bindings(&el.pat, cond_t))
        } else {
            Vec::new()
        };
        self.visit_block(&node.body);
        self.restore_scoped(saved);
    }

    fn visit_expr_match(&mut self, node: &'ast ExprMatch) {
        self.visit_expr(&node.expr);
        let scrut_t = expr_uses_tainted(&node.expr, self.tainted, self.ret_taint);
        for arm in &node.arms {
            let saved = self.bind_scoped(pat_bindings(&arm.pat, scrut_t));
            if let Some((_, guard)) = &arm.guard {
                self.visit_expr(guard);
            }
            self.visit_expr(&arm.body);
            self.restore_scoped(saved);
        }
    }

    fn visit_expr_for_loop(&mut self, node: &'ast ExprForLoop) {
        self.visit_expr(&node.expr);
        let mut bindings: Option<Vec<(String, bool)>> = None;
        if let Pat::Tuple(pt) = unwrap_pat_type_and_parens(&node.pat) {
            let iter_expr = unwrap_ref_or_cast(&node.expr);
            // Case 1: `for (col, val) in [("a", &self.a), ("b", &self.b)]`
            if let Expr::Array(arr) = iter_expr
                && !arr.elems.is_empty()
                && arr.elems.iter().all(|e| matches!(unwrap_parens(e), Expr::Tuple(_)))
            {
                let mut b = Vec::new();
                for (slot, elem_pat) in pt.elems.iter().enumerate() {
                    let slot_tainted = arr.elems.iter().any(|e| {
                        matches!(unwrap_parens(e), Expr::Tuple(t) if t.elems.iter().nth(slot)
                            .is_some_and(|item| expr_uses_tainted(item, self.tainted, self.ret_taint)))
                    });
                    b.extend(pat_bindings(elem_pat, slot_tainted));
                }
                bindings = Some(b);
            } else if let Some(place) = place_key_of_expr(strip_item_adapters(iter_expr))
                && !self.tainted.contains(&place)
                && !ancestor_tainted(self.tainted, &place)
                && let Some(tainted_slots) = tuple_slot_taint(self.tainted, &place)
            {
                // Case 2: `for (col, val) in &fields` where `fields` (a local, or a
                // parameter's field such as `edge.sets`) holds per-slot taint `fields.#<slot>`.
                let mut b = Vec::new();
                for (slot, elem_pat) in pt.elems.iter().enumerate() {
                    b.extend(pat_bindings(elem_pat, tainted_slots.contains(&slot)));
                }
                bindings = Some(b);
            }
        }
        let bindings = bindings.unwrap_or_else(|| {
            pat_bindings(&node.pat, expr_uses_tainted(&node.expr, self.tainted, self.ret_taint))
        });
        let saved = self.bind_scoped(bindings);
        self.visit_block(&node.body);
        self.restore_scoped(saved);
    }

    fn visit_expr_closure(&mut self, node: &'ast ExprClosure) {
        // Respect closure parameter shadowing so an inner `|r|` does not taint
        // from an outer parameter `r`.
        let mut bindings = Vec::new();
        for pat in &node.inputs {
            bindings.extend(pat_bindings(pat, false));
        }
        let saved = self.bind_scoped(bindings);
        self.visit_expr(&node.body);
        self.restore_scoped(saved);
    }
}

impl TaintPropagator<'_, '_> {
    fn propagate_write_macro(&mut self, mac: &syn::Macro) {
        let is_write = mac
            .path
            .segments
            .last()
            .is_some_and(|s| matches!(s.ident.to_string().as_str(), "write" | "writeln"));
        if !is_write {
            return;
        }
        if let Some(args) = &macro_parse(mac).args
            && args.len() >= 2
            && macro_tokens_use_tainted(mac, self.tainted, self.ret_taint)
            && let Some(var) = root_ident_of_expr(&args[0])
        {
            self.tainted.insert(var);
        }
    }
}

/// Per-slot taint of a place built from tuple pushes (`place.#<slot>` keys), or
/// `None` when nothing under the place is tainted or a non-slot sub-path is.
fn tuple_slot_taint(tainted: &BTreeSet<String>, place: &str) -> Option<BTreeSet<usize>> {
    let mut slots = BTreeSet::new();
    for rest in tainted_fields_of_var(place, tainted) {
        let slot = rest.split('.').next().and_then(|s| s.strip_prefix('#')).and_then(|n| n.parse().ok())?;
        slots.insert(slot);
    }
    (!slots.is_empty()).then_some(slots)
}

fn unwrap_try_and_parens(mut expr: &Expr) -> &Expr {
    loop {
        match expr {
            Expr::Paren(p) => expr = &p.expr,
            Expr::Group(g) => expr = &g.expr,
            Expr::Try(t) => expr = &t.expr,
            _ => return expr,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
enum ParamSqlFlow {
    /// The whole parameter (or an opaque/method-called part of it) flows to SQL.
    Whole,
    /// Only these specific named/tuple fields of the parameter flow to SQL.
    Fields(BTreeSet<String>),
}

impl ParamSqlFlow {
    fn merge(&mut self, other: ParamSqlFlow) {
        match (&mut *self, other) {
            (ParamSqlFlow::Whole, _) => {}
            (_, ParamSqlFlow::Whole) => *self = ParamSqlFlow::Whole,
            (ParamSqlFlow::Fields(a), ParamSqlFlow::Fields(b)) => a.extend(b),
        }
    }
}

fn arg_matches_sql_flow(
    arg: &Expr,
    flow: &ParamSqlFlow,
    tainted: &BTreeSet<String>,
    ret_taint: &LocalReturnTaint,
) -> bool {
    match flow {
        ParamSqlFlow::Whole => expr_uses_tainted(arg, tainted, ret_taint),
        ParamSqlFlow::Fields(fields) => {
            if let Some(arg_fields) = eval_struct_expr_taint(arg, tainted, ret_taint) {
                return arg_fields.iter().any(|a| fields.iter().any(|f| field_paths_overlap(a, f)));
            }
            expr_uses_tainted(arg, tainted, ret_taint)
        }
    }
}

/// Known local SQL helpers: name -> (kind, SQL-taking parameter index -> flow).
type KnownHelpers = BTreeMap<String, (HelperKind, BTreeMap<usize, ParamSqlFlow>)>;

/// Record `let g = helper;` so a later `g(..)` resolves to `helper`.
fn record_helper_alias(node: &Local, helpers: &KnownHelpers, aliases: &mut BTreeMap<String, String>) {
    if let Some(init) = &node.init
        && let Expr::Path(ep) = unwrap_ref_or_cast(&init.expr)
        && ep.qself.is_none()
        && let Some(last) = ep.path.segments.last()
    {
        let target = last.ident.to_string();
        if helpers.contains_key(&target) {
            let mut vars = Vec::new();
            collect_pat_idents(&node.pat, &mut vars);
            for v in vars {
                aliases.insert(v, target.clone());
            }
        }
    }
}

/// Does `recv.helper(..)` pass a tainted value in a SQL-taking slot?
fn method_call_hits_helper(
    node: &ExprMethodCall,
    helpers: &KnownHelpers,
    tainted: &BTreeSet<String>,
    ret_taint: &LocalReturnTaint,
) -> bool {
    let Some((HelperKind::Method, flows)) = helpers.get(&node.method.to_string()) else { return false };
    flows.iter().any(|(&idx, flow)| {
        node.args.iter().nth(idx).is_some_and(|arg| arg_matches_sql_flow(arg, flow, tainted, ret_taint))
    })
}

/// Does `helper(..)` / `Type::helper(..)` / `alias(..)` pass a tainted value in
/// a SQL-taking slot?
fn call_hits_helper(
    node: &ExprCall,
    helpers: &KnownHelpers,
    aliases: &BTreeMap<String, String>,
    tainted: &BTreeSet<String>,
    ret_taint: &LocalReturnTaint,
) -> bool {
    let Expr::Path(ep) = unwrap_parens(&node.func) else { return false };
    let Some(last) = ep.path.segments.last() else { return false };
    if ep.qself.is_some() {
        return false;
    }
    let raw_name = last.ident.to_string();
    let resolved = if ep.path.segments.len() == 1 {
        aliases.get(&raw_name).cloned().unwrap_or(raw_name)
    } else {
        raw_name
    };
    let Some((kind, flows)) = helpers.get(&resolved) else { return false };
    let shift = match kind {
        HelperKind::Method if ep.path.segments.len() >= 2 => 1usize,
        HelperKind::Fn | HelperKind::Closure => 0usize,
        _ => return false,
    };
    flows.iter().any(|(&idx, flow)| {
        node.args
            .iter()
            .nth(idx + shift)
            .is_some_and(|arg| arg_matches_sql_flow(arg, flow, tainted, ret_taint))
    })
}

/// Does `helper!(..)` pass a tainted value in a SQL-taking position?
fn macro_hits_helper(
    mac: &syn::Macro,
    helpers: &KnownHelpers,
    tainted: &BTreeSet<String>,
    ret_taint: &LocalReturnTaint,
) -> bool {
    let Some(last) = mac.path.segments.last() else { return false };
    let Some((HelperKind::Macro, flows)) = helpers.get(&last.ident.to_string()) else { return false };
    let idxs: BTreeSet<usize> = flows.keys().copied().collect();
    macro_call_uses_tainted_at_indices(mac, &idxs, tainted, ret_taint)
}

/// Post-propagation check: does `body` call any known local SQL helper
/// (including local fn-pointer aliases and `macro_rules!` helpers) with a value
/// from the final taint set in a SQL-taking slot?
struct LocalHelperTaintChecker<'a> {
    helpers: &'a KnownHelpers,
    tainted: &'a BTreeSet<String>,
    ret_taint: &'a LocalReturnTaint,
    aliases: BTreeMap<String, String>,
    hit: bool,
}

impl<'ast> Visit<'ast> for LocalHelperTaintChecker<'_> {
    fn visit_item(&mut self, node: &'ast Item) {
        if item_has_cfg_test(node) || self.hit {
            return;
        }
        visit::visit_item(self, node);
    }

    fn visit_local(&mut self, node: &'ast Local) {
        if attrs_have_cfg_test(&node.attrs) || self.hit {
            return;
        }
        record_helper_alias(node, self.helpers, &mut self.aliases);
        visit::visit_local(self, node);
    }

    fn visit_expr_method_call(&mut self, node: &'ast ExprMethodCall) {
        if self.hit {
            return;
        }
        if method_call_hits_helper(node, self.helpers, self.tainted, self.ret_taint) {
            self.hit = true;
            return;
        }
        visit::visit_expr_method_call(self, node);
    }

    fn visit_expr_call(&mut self, node: &'ast ExprCall) {
        if self.hit {
            return;
        }
        if call_hits_helper(node, self.helpers, &self.aliases, self.tainted, self.ret_taint) {
            self.hit = true;
            return;
        }
        visit::visit_expr_call(self, node);
    }

    fn visit_macro(&mut self, node: &'ast syn::Macro) {
        if self.hit {
            return;
        }
        if macro_hits_helper(node, self.helpers, self.tainted, self.ret_taint) {
            self.hit = true;
            return;
        }
        visit_macro_with(node, self);
    }

    fn visit_stmt(&mut self, node: &'ast Stmt) {
        if stmt_has_cfg_test(node) || self.hit {
            return;
        }
        visit::visit_stmt(self, node);
    }
}

fn macro_call_uses_tainted_at_indices(
    mac: &syn::Macro,
    idxs: &BTreeSet<usize>,
    tainted: &BTreeSet<String>,
    ret_taint: &LocalReturnTaint,
) -> bool {
    if idxs.is_empty() {
        return false;
    }
    if let Some(args) = &macro_parse(mac).args {
        return idxs
            .iter()
            .any(|&i| args.iter().nth(i).is_some_and(|e| expr_uses_tainted(e, tainted, ret_taint)));
    }
    let parts = split_tt_commas(mac.tokens.clone());
    idxs.iter().any(|&i| parts.get(i).is_some_and(|ts| tokens_use_tainted_raw(ts.clone(), tainted)))
}

#[derive(Clone)]
enum CallableBody<'a> {
    Block(&'a syn::Block),
    Expr(&'a Expr),
}

#[derive(Clone)]
struct CandidateCallable<'a> {
    name: String,
    vis: HelperVis,
    kind: HelperKind,
    is_pub: bool,
    line: usize,
    explicit_arity: usize,
    params: Vec<(usize, String)>,
    body: CallableBody<'a>,
    /// Whether the return type can carry text (`false` for `()`, `bool`, and
    /// numbers, also inside `Result`/`Option`): such returns get no taint.
    ret_carrier: bool,
}

/// Can a value of this return type carry SQL text? `()`, `bool`, and numeric
/// primitives cannot, also when wrapped in `Result<T, _>` / `Option<T>` or a
/// `*Result<T>` alias; everything else (including `Value`, structs, and
/// generics) is assumed to.
fn return_type_carries_text(ret: &ReturnType) -> bool {
    match ret {
        ReturnType::Default => false,
        ReturnType::Type(_, ty) => type_carries_text(ty),
    }
}

fn type_carries_text(ty: &Type) -> bool {
    match ty {
        Type::Tuple(t) => t.elems.iter().any(type_carries_text),
        Type::Paren(p) => type_carries_text(&p.elem),
        Type::Group(g) => type_carries_text(&g.elem),
        Type::Never(_) => false,
        Type::Path(tp) => {
            let Some(last) = tp.path.segments.last() else { return true };
            let name = last.ident.to_string();
            if name == "Option" || name.ends_with("Result") {
                return match &last.arguments {
                    syn::PathArguments::AngleBracketed(ab) => match ab.args.first() {
                        Some(syn::GenericArgument::Type(inner)) => type_carries_text(inner),
                        _ => true,
                    },
                    _ => true,
                };
            }
            !is_non_sql_carrier_type(ty)
        }
        _ => true,
    }
}

/// Database / hub runtime handles and scalar numeric/bool primitives that are
/// never SQL text carriers. Skipping them prevents a connection handle's own
/// query results or a clamped integer `LIMIT` from falsely flagging a function,
/// while still tracing every struct, newtype, enum, `impl Display`, generic `T`,
/// and string type.
fn is_non_sql_carrier_type(ty: &Type) -> bool {
    match ty {
        Type::Reference(r) => is_non_sql_carrier_type(&r.elem),
        Type::Paren(p) => is_non_sql_carrier_type(&p.elem),
        Type::Group(g) => is_non_sql_carrier_type(&g.elem),
        Type::Path(tp) => tp.path.segments.last().is_some_and(|s| {
            matches!(
                s.ident.to_string().as_str(),
                "Connection"
                    | "Transaction"
                    | "WriteTx"
                    | "Savepoint"
                    | "Db"
                    | "Hub"
                    | "ToolCtx"
                    | "AppState"
                    | "Registry"
                    | "bool"
                    | "i8"
                    | "i16"
                    | "i32"
                    | "i64"
                    | "i128"
                    | "isize"
                    | "u8"
                    | "u16"
                    | "u32"
                    | "u64"
                    | "u128"
                    | "usize"
                    | "f32"
                    | "f64"
            )
        }),
        _ => false,
    }
}

fn extract_fn_params(inputs: &Punctuated<FnArg, Token![,]>) -> (Vec<(usize, String)>, bool, usize) {
    let mut out = Vec::new();
    let mut has_self = false;
    let mut arg_idx = 0usize;
    for arg in inputs {
        match arg {
            FnArg::Receiver(_) => has_self = true,
            FnArg::Typed(pt) => {
                if !is_non_sql_carrier_type(&pt.ty) {
                    let mut names = Vec::new();
                    collect_pat_idents(&pt.pat, &mut names);
                    for n in names {
                        out.push((arg_idx, n));
                    }
                }
                arg_idx += 1;
            }
        }
    }
    (out, has_self, arg_idx)
}

fn extract_closure_params(inputs: &Punctuated<Pat, Token![,]>) -> Vec<(usize, String)> {
    let mut out = Vec::new();
    for (arg_idx, pat) in inputs.iter().enumerate() {
        let mut names = Vec::new();
        collect_pat_idents(pat, &mut names);
        for n in names {
            out.push((arg_idx, n));
        }
    }
    out
}

/// Collect all functions, methods, closures, and `macro_rules!` SQL wrappers in a file.
struct CallableCollector<'ast> {
    callables: Vec<CandidateCallable<'ast>>,
    macros: Vec<DetectedHelper>,
    enclosing_fn: Option<String>,
    in_pub_trait_impl: bool,
}

impl<'ast> CallableCollector<'ast> {
    fn new() -> Self {
        Self { callables: Vec::new(), macros: Vec::new(), enclosing_fn: None, in_pub_trait_impl: false }
    }
}

impl<'ast> Visit<'ast> for CallableCollector<'ast> {
    fn visit_item(&mut self, node: &'ast Item) {
        if item_has_cfg_test(node) {
            return;
        }
        visit::visit_item(self, node);
    }

    fn visit_item_trait(&mut self, node: &'ast ItemTrait) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        let prev = self.in_pub_trait_impl;
        self.in_pub_trait_impl = matches!(node.vis, Visibility::Public(_));
        visit::visit_item_trait(self, node);
        self.in_pub_trait_impl = prev;
    }

    fn visit_item_impl(&mut self, node: &'ast ItemImpl) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        let prev = self.in_pub_trait_impl;
        self.in_pub_trait_impl = node.trait_.is_some();
        visit::visit_item_impl(self, node);
        self.in_pub_trait_impl = prev;
    }

    fn visit_item_fn(&mut self, node: &'ast ItemFn) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        let name = node.sig.ident.to_string();
        let (vis, is_pub) = vis_of(&node.vis, false);
        let (params, has_self, explicit_arity) = extract_fn_params(&node.sig.inputs);
        self.callables.push(CandidateCallable {
            name: name.clone(),
            vis,
            kind: if has_self { HelperKind::Method } else { HelperKind::Fn },
            is_pub,
            line: node.sig.ident.span().start().line,
            explicit_arity,
            params,
            body: CallableBody::Block(&node.block),
            ret_carrier: return_type_carries_text(&node.sig.output),
        });
        let prev_fn = self.enclosing_fn.replace(name);
        let prev_trait = self.in_pub_trait_impl;
        self.in_pub_trait_impl = false;
        visit::visit_block(self, &node.block);
        self.enclosing_fn = prev_fn;
        self.in_pub_trait_impl = prev_trait;
    }

    fn visit_impl_item_fn(&mut self, node: &'ast ImplItemFn) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        let name = node.sig.ident.to_string();
        let (vis, is_pub) = vis_of(&node.vis, self.in_pub_trait_impl);
        let (params, has_self, explicit_arity) = extract_fn_params(&node.sig.inputs);
        self.callables.push(CandidateCallable {
            name: name.clone(),
            vis,
            kind: if has_self { HelperKind::Method } else { HelperKind::Fn },
            is_pub,
            line: node.sig.ident.span().start().line,
            explicit_arity,
            params,
            body: CallableBody::Block(&node.block),
            ret_carrier: return_type_carries_text(&node.sig.output),
        });
        let prev_fn = self.enclosing_fn.replace(name);
        let prev_trait = self.in_pub_trait_impl;
        self.in_pub_trait_impl = false;
        visit::visit_block(self, &node.block);
        self.enclosing_fn = prev_fn;
        self.in_pub_trait_impl = prev_trait;
    }

    fn visit_trait_item_fn(&mut self, node: &'ast TraitItemFn) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        if let Some(body) = &node.default {
            let name = node.sig.ident.to_string();
            let (vis, is_pub) =
                if self.in_pub_trait_impl { (HelperVis::Pub, true) } else { (HelperVis::Private, false) };
            let (params, has_self, explicit_arity) = extract_fn_params(&node.sig.inputs);
            self.callables.push(CandidateCallable {
                name: name.clone(),
                vis,
                kind: if has_self { HelperKind::Method } else { HelperKind::Fn },
                is_pub,
                line: node.sig.ident.span().start().line,
                explicit_arity,
                params,
                body: CallableBody::Block(body),
                ret_carrier: return_type_carries_text(&node.sig.output),
            });
            let prev_fn = self.enclosing_fn.replace(name);
            let prev_trait = self.in_pub_trait_impl;
            self.in_pub_trait_impl = false;
            visit::visit_block(self, body);
            self.enclosing_fn = prev_fn;
            self.in_pub_trait_impl = prev_trait;
        }
    }

    fn visit_local(&mut self, node: &'ast Local) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        if let Some(init) = &node.init
            && let Expr::Closure(ExprClosure { inputs, body, .. }) = unwrap_parens(&init.expr)
        {
            let mut names = Vec::new();
            collect_pat_idents(&node.pat, &mut names);
            let name = names
                .into_iter()
                .next()
                .unwrap_or_else(|| format!("{}::closure", self.enclosing_fn.as_deref().unwrap_or("<top>")));
            let explicit_arity = inputs.len();
            let params = extract_closure_params(inputs);
            self.callables.push(CandidateCallable {
                name,
                vis: HelperVis::Private,
                kind: HelperKind::Closure,
                is_pub: false,
                line: node.pat.span().start().line,
                explicit_arity,
                params,
                body: CallableBody::Expr(body),
                ret_carrier: true,
            });
        }
        visit::visit_local(self, node);
    }

    fn visit_item_macro(&mut self, node: &'ast ItemMacro) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        if node.mac.path.is_ident("macro_rules")
            && let Some(ident) = &node.ident
        {
            let (has_sql_call, sql_param_indices) = analyze_macro_rules_sql(node.mac.tokens.clone());
            if has_sql_call {
                let is_exported = attrs_have_macro_export(&node.attrs);
                self.macros.push(DetectedHelper {
                    name: ident.to_string(),
                    vis: if is_exported { HelperVis::Pub } else { HelperVis::PubCrate },
                    kind: HelperKind::Macro,
                    is_pub: is_exported,
                    line: ident.span().start().line,
                    sql_param_indices,
                });
            }
        }
    }
}

/// Analyze a `macro_rules!` body's arms `(pattern) => { expansion }` for SQL calls.
/// Returns `(has_sql_call, sql_arg_indices)` where `sql_arg_indices` are the
/// comma-separated matcher positions whose `$metavar` reaches a SQL argument.
fn analyze_macro_rules_sql(stream: TokenStream) -> (bool, Vec<usize>) {
    let arms = extract_macro_rule_arms(stream);
    let mut has_sql = false;
    let mut sql_indices = BTreeSet::new();
    for (pat, body) in arms {
        let pat_vars = extract_macro_pat_metavar_indices(pat);
        let (arm_sql, used_vars) =
            parse_macro_body_for_sql(body.clone()).unwrap_or_else(|| scan_macro_body_tokens_for_sql(body));
        has_sql |= arm_sql;
        for mv in used_vars {
            if let Some(&idx) = pat_vars.get(&mv) {
                sql_indices.insert(idx);
            }
        }
    }
    (has_sql, sql_indices.into_iter().collect())
}

fn extract_macro_rule_arms(stream: TokenStream) -> Vec<(TokenStream, TokenStream)> {
    let tts: Vec<TokenTree> = stream.into_iter().collect();
    let mut arms = Vec::new();
    let mut i = 0;
    while i < tts.len() {
        if let TokenTree::Group(pat_group) = &tts[i]
            && let Some(TokenTree::Punct(p1)) = tts.get(i + 1)
            && p1.as_char() == '='
            && let Some(TokenTree::Punct(p2)) = tts.get(i + 2)
            && p2.as_char() == '>'
            && let Some(TokenTree::Group(body_group)) = tts.get(i + 3)
        {
            arms.push((pat_group.stream(), body_group.stream()));
            i += 4;
            continue;
        }
        i += 1;
    }
    arms
}

fn extract_macro_rule_bodies(stream: TokenStream) -> Vec<TokenStream> {
    extract_macro_rule_arms(stream).into_iter().map(|(_, b)| b).collect()
}

fn extract_macro_pat_metavar_indices(pat: TokenStream) -> BTreeMap<String, usize> {
    let mut map = BTreeMap::new();
    for (idx, part) in split_tt_commas(pat).into_iter().enumerate() {
        let mut names = BTreeSet::new();
        collect_tt_metavars(part, &mut names);
        for n in names {
            map.insert(n, idx);
        }
    }
    map
}

/// Substitute a `macro_rules!` transcriber's metavariables so it parses as
/// Rust: `$name` becomes the ident `__mv_name`, and a repetition
/// `$( ... ) sep? op` is replaced by one copy of its contents.
fn substitute_metavars(stream: TokenStream) -> TokenStream {
    let tts: Vec<TokenTree> = stream.into_iter().collect();
    let mut out: Vec<TokenTree> = Vec::new();
    let mut i = 0;
    while i < tts.len() {
        match &tts[i] {
            TokenTree::Punct(p) if p.as_char() == '$' => match tts.get(i + 1) {
                Some(TokenTree::Ident(id)) => {
                    out.push(TokenTree::Ident(proc_macro2::Ident::new(
                        &format!("{METAVAR_PREFIX}{id}"),
                        id.span(),
                    )));
                    i += 2;
                }
                Some(TokenTree::Group(g)) if g.delimiter() == Delimiter::Parenthesis => {
                    out.extend(substitute_metavars(g.stream()));
                    i += 2;
                    let is_rep_op = |t: Option<&TokenTree>| matches!(t, Some(TokenTree::Punct(op)) if matches!(op.as_char(), '*' | '+' | '?'));
                    if is_rep_op(tts.get(i)) {
                        i += 1;
                    } else if is_rep_op(tts.get(i + 1)) {
                        i += 2;
                    }
                }
                _ => {
                    out.push(tts[i].clone());
                    i += 1;
                }
            },
            TokenTree::Group(g) => {
                let mut ng = proc_macro2::Group::new(g.delimiter(), substitute_metavars(g.stream()));
                ng.set_span(g.span());
                out.push(TokenTree::Group(ng));
                i += 1;
            }
            other => {
                out.push(other.clone());
                i += 1;
            }
        }
    }
    out.into_iter().collect()
}

const METAVAR_PREFIX: &str = "__mv_";

/// Parse one `macro_rules!` arm body with `syn` (after metavariable
/// substitution) and collect its SQL calls with the same visitor as ordinary
/// code. Returns `(has_sql_call, metavars_reaching_sql_arg)`, or `None` when
/// the body does not parse (the token scan below is the fallback).
fn parse_macro_body_for_sql(body: TokenStream) -> Option<(bool, BTreeSet<String>)> {
    let tokens = substitute_metavars(body);
    // Leaked so macros nested in the body keep unique addresses for `macro_parse`.
    let block: &'static syn::Block =
        Box::leak(Box::new(syn::parse2::<syn::Block>(quote_braces(tokens)).ok()?));
    let mut direct = DirectSqlCollector::new();
    direct.visit_block(block);
    let sites = direct.finish();
    let mut used = BTreeSet::new();
    for site in &sites {
        if let DirectSqlSite::Call(arg, _) = site {
            let mut names = NameCollector::default();
            names.visit_expr(arg);
            used.extend(names.0.iter().filter_map(|n| n.strip_prefix(METAVAR_PREFIX)).map(str::to_string));
            // `format!("..{q}..")` captures name the metavariable only inside the string.
            used.extend(
                arg_format_captures(arg)
                    .into_iter()
                    .filter_map(|n| n.strip_prefix(METAVAR_PREFIX).map(str::to_string)),
            );
        }
    }
    Some((!sites.is_empty(), used))
}

/// `{ident}` captures of every `format!`-family macro inside `expr`.
fn arg_format_captures(expr: &Expr) -> Vec<String> {
    struct Caps(Vec<String>);
    impl<'ast> Visit<'ast> for Caps {
        fn visit_macro(&mut self, node: &'ast syn::Macro) {
            let parsed = macro_parse(node);
            self.0.extend(parsed.fmt_captures.iter().cloned());
            visit_macro_with(node, self);
        }
    }
    let mut caps = Caps(Vec::new());
    caps.visit_expr(expr);
    caps.0
}

/// Scan a `macro_rules!` expansion token stream (which may contain `$var`
/// metavariables so it is not always valid Rust before substitution) for
/// direct SQL method calls, UFCS calls, or `Batch::new`. Returns
/// `(has_sql_call, metavars_reaching_sql_arg)`.
fn scan_macro_body_tokens_for_sql(stream: TokenStream) -> (bool, BTreeSet<String>) {
    let tts: Vec<TokenTree> = stream.into_iter().collect();
    let mut has_sql = false;
    let mut used_metavars = BTreeSet::new();
    let mut i = 0;
    while i < tts.len() {
        // Method call: `. <sql_method> ( args )`
        if let TokenTree::Punct(p) = &tts[i]
            && p.as_char() == '.'
            && let Some(TokenTree::Ident(m)) = tts.get(i + 1)
            && let Some(expected) = expected_sql_method_args(&m.to_string())
        {
            let after_tf = skip_tt_turbofish(&tts, i + 2);
            if let Some(TokenTree::Group(g)) = tts.get(after_tf)
                && g.delimiter() == Delimiter::Parenthesis
            {
                let args = split_tt_commas(g.stream());
                if args.len() == expected {
                    has_sql = true;
                    collect_tt_metavars(args[0].clone(), &mut used_metavars);
                }
            }
        }
        // UFCS call: `:: <sql_method> ( receiver, sql, ... )` or `Batch :: new ( conn, sql )`
        if let TokenTree::Punct(p1) = &tts[i]
            && p1.as_char() == ':'
            && let Some(TokenTree::Punct(p2)) = tts.get(i + 1)
            && p2.as_char() == ':'
            && let Some(TokenTree::Ident(m)) = tts.get(i + 2)
        {
            let m_str = m.to_string();
            let prev_is_batch = i > 0 && matches!(&tts[i - 1], TokenTree::Ident(b) if b == "Batch");
            let expected_arity = if prev_is_batch && m_str == "new" {
                Some(2)
            } else {
                expected_sql_method_args(&m_str).map(|n| n + 1)
            };
            if let Some(arity) = expected_arity {
                let after_tf = skip_tt_turbofish(&tts, i + 3);
                if let Some(TokenTree::Group(g)) = tts.get(after_tf)
                    && g.delimiter() == Delimiter::Parenthesis
                {
                    let args = split_tt_commas(g.stream());
                    if args.len() == arity {
                        has_sql = true;
                        collect_tt_metavars(args[1].clone(), &mut used_metavars);
                    }
                }
            }
        }
        if let TokenTree::Group(g) = &tts[i] {
            let (s, mvs) = scan_macro_body_tokens_for_sql(g.stream());
            has_sql |= s;
            used_metavars.extend(mvs);
        }
        i += 1;
    }
    (has_sql, used_metavars)
}

fn skip_tt_turbofish(tts: &[TokenTree], i: usize) -> usize {
    if matches!(tts.get(i), Some(TokenTree::Punct(p)) if p.as_char() == ':')
        && matches!(tts.get(i + 1), Some(TokenTree::Punct(p)) if p.as_char() == ':')
        && matches!(tts.get(i + 2), Some(TokenTree::Punct(p)) if p.as_char() == '<')
    {
        let mut depth = 0usize;
        let mut j = i + 2;
        while j < tts.len() {
            if let TokenTree::Punct(p) = &tts[j] {
                if p.as_char() == '<' {
                    depth += 1;
                } else if p.as_char() == '>' {
                    depth -= 1;
                    if depth == 0 {
                        return j + 1;
                    }
                }
            }
            j += 1;
        }
    }
    i
}

fn collect_tt_metavars(stream: TokenStream, out: &mut BTreeSet<String>) {
    let tts: Vec<TokenTree> = stream.into_iter().collect();
    for (i, tt) in tts.iter().enumerate() {
        match tt {
            TokenTree::Punct(p) if p.as_char() == '$' => {
                if let Some(TokenTree::Ident(id)) = tts.get(i + 1) {
                    out.insert(id.to_string());
                }
            }
            TokenTree::Group(g) => collect_tt_metavars(g.stream(), out),
            _ => {}
        }
    }
}

/// Collect all return expressions of a block (explicit `return <expr>` and
/// final tail expression), unwrapping `Ok(...)` / `Some(...)` wrappers so
/// `Ok((guard, params))` exposes its tuple slots directly.
struct ReturnExprCollector<'ast> {
    exprs: Vec<&'ast Expr>,
}

impl<'ast> Visit<'ast> for ReturnExprCollector<'ast> {
    fn visit_item(&mut self, _node: &'ast Item) {
        // Do not descend into nested functions.
    }

    fn visit_expr_closure(&mut self, _node: &'ast ExprClosure) {
        // Do not descend into inner closures' returns.
    }

    fn visit_expr_return(&mut self, node: &'ast syn::ExprReturn) {
        if let Some(e) = &node.expr {
            self.exprs.push(e);
        }
    }
}

fn unwrap_result_wrapper(expr: &Expr) -> &Expr {
    let e = unwrap_parens(expr);
    if let Expr::Call(c) = e
        && c.args.len() == 1
        && let Expr::Path(ep) = unwrap_parens(&c.func)
        && ep.path.segments.last().is_some_and(|s| matches!(s.ident.to_string().as_str(), "Ok" | "Some"))
    {
        return unwrap_parens(&c.args[0]);
    }
    e
}

fn collect_return_exprs<'a>(body: &CallableBody<'a>) -> Vec<&'a Expr> {
    let mut col = ReturnExprCollector { exprs: Vec::new() };
    match body {
        CallableBody::Block(b) => {
            col.visit_block(b);
            if let Some(Stmt::Expr(tail, None)) = b.stmts.last() {
                col.exprs.push(tail);
            }
        }
        CallableBody::Expr(e) => {
            col.visit_expr(e);
            col.exprs.push(e);
        }
    }
    col.exprs
}

/// Inspect how a parameter `param` is referenced in `body`: collects every
/// `param.<field>` access and records whether `param` is ever referenced as a
/// whole (outside a direct field projection `param.<field>`).
struct ParamFieldUsageVisitor<'a> {
    param: &'a str,
    used_whole: bool,
    fields: BTreeSet<String>,
}

impl<'ast> Visit<'ast> for ParamFieldUsageVisitor<'_> {
    fn visit_item(&mut self, node: &'ast Item) {
        if item_has_cfg_test(node) {
            return;
        }
        visit::visit_item(self, node);
    }

    fn visit_expr_field(&mut self, node: &'ast ExprField) {
        if let Expr::Path(ep) = unwrap_parens(&node.base)
            && ep.qself.is_none()
            && ep.path.segments.len() == 1
            && ep.path.segments[0].ident == self.param
        {
            self.fields.insert(member_name(&node.member));
            return;
        }
        visit::visit_expr_field(self, node);
    }

    fn visit_expr_path(&mut self, node: &'ast ExprPath) {
        if node.qself.is_none() && node.path.segments.len() == 1 && node.path.segments[0].ident == self.param
        {
            self.used_whole = true;
        }
        visit::visit_expr_path(self, node);
    }

    fn visit_expr_macro(&mut self, node: &'ast ExprMacro) {
        self.scan_macro(&node.mac);
    }

    fn visit_stmt(&mut self, node: &'ast Stmt) {
        if stmt_has_cfg_test(node) {
            return;
        }
        if let Stmt::Macro(sm) = node {
            self.scan_macro(&sm.mac);
            return;
        }
        visit::visit_stmt(self, node);
    }
}

impl ParamFieldUsageVisitor<'_> {
    fn scan_macro(&mut self, mac: &syn::Macro) {
        let parsed = macro_parse(mac);
        if parsed.fmt_captures.iter().any(|c| c == self.param) {
            self.used_whole = true;
        }
        if let Some(exprs) = &parsed.args {
            for e in exprs {
                self.visit_expr(e);
            }
        } else {
            let mut single = BTreeSet::new();
            single.insert(self.param.to_string());
            if tokens_use_tainted_raw(mac.tokens.clone(), &single) {
                self.used_whole = true;
            }
        }
    }
}

/// Compute per-tuple-slot and per-struct-field return taint for `callables`,
/// layering them on top of an already-computed `base` (e.g. non-private
/// builders from other modules in the same crate) so each file only analyzes
/// its own callables once instead of re-analyzing the whole crate per file.
fn compute_local_return_taint(
    callables: &[CandidateCallable<'_>],
    base: Option<Rc<LocalReturnTaint>>,
) -> LocalReturnTaint {
    let local_keys: Rc<BTreeSet<SummaryKey>> = Rc::new(
        callables
            .iter()
            .filter(|c| c.kind != HelperKind::Closure && c.kind != HelperKind::Macro)
            .map(|c| (c.name.clone(), c.kind == HelperKind::Method, c.explicit_arity))
            .collect(),
    );
    let mut summary = LocalReturnTaint::layered(base.clone(), local_keys.clone());
    let (no_sql_args, no_helpers) = (HashSet::new(), KnownHelpers::new());
    for _ in 0..4 {
        let mut next = LocalReturnTaint::layered(base.clone(), local_keys.clone());
        let mut non_struct_keys: BTreeSet<(String, bool, usize)> = BTreeSet::new();
        for c in callables {
            if c.kind == HelperKind::Closure || c.kind == HelperKind::Macro {
                continue;
            }
            let has_self = c.kind == HelperKind::Method;
            let key = (c.name.clone(), has_self, c.explicit_arity);
            let slot_entry = next.slots.entry(key.clone()).or_default();
            if !c.ret_carrier {
                // Known, and no parameter taints the (text-free) result.
                non_struct_keys.insert(key);
                continue;
            }

            let mut seeds: Vec<(usize, String)> = Vec::new();
            if has_self {
                seeds.push((0, "self".to_string()));
                for (p_idx, p_name) in &c.params {
                    seeds.push((*p_idx + 1, p_name.clone()));
                }
            } else {
                seeds.extend(c.params.iter().cloned());
            }

            let ret_exprs = collect_return_exprs(&c.body);
            let is_struct_fn = !ret_exprs.is_empty()
                && ret_exprs.iter().all(|r| is_struct_shaped_ret(r, has_self, &summary));
            if !is_struct_fn {
                non_struct_keys.insert(key.clone());
            }
            let mut struct_sum = if is_struct_fn { Some(StructReturnSummary::default()) } else { None };

            for (slot_param_idx, seed_name) in seeds {
                let mut tainted = BTreeSet::new();
                tainted.insert(seed_name.clone());
                let mut probe = Some(FlowProbe::new(&no_sql_args, &no_helpers));
                for _ in 0..6 {
                    let before = tainted.len();
                    let mut prop =
                        TaintPropagator { tainted: &mut tainted, ret_taint: &summary, probe: probe.take() };
                    match c.body {
                        CallableBody::Block(b) => prop.visit_block(b),
                        CallableBody::Expr(e) => prop.visit_expr(e),
                    }
                    probe = prop.probe.take();
                    if tainted.len() == before {
                        break;
                    }
                }
                let live_at_return = probe.map(|p| p.returns).unwrap_or_default();
                for ret in &ret_exprs {
                    if is_diverging_expr(ret) {
                        continue;
                    }
                    // A `return` inside a scope sees that scope's bindings.
                    let at_return;
                    let tainted: &BTreeSet<String> = match live_at_return.get(&expr_addr(ret)) {
                        Some(live) => {
                            at_return = tainted.union(live).cloned().collect::<BTreeSet<_>>();
                            &at_return
                        }
                        None => &tainted,
                    };
                    if let Some(slot_ts) = eval_tuple_slots_tainted(ret, tainted, &summary) {
                        for (slot, is_t) in slot_ts.into_iter().enumerate() {
                            if is_t {
                                slot_entry.entry(slot).or_default().insert(slot_param_idx);
                            }
                        }
                    } else if expr_uses_tainted(unwrap_result_wrapper(ret), tainted, &summary) {
                        slot_entry.entry(0).or_default().insert(slot_param_idx);
                    }

                    if let Some(ss) = &mut struct_sum {
                        if has_self && slot_param_idx == 0 && ret_passes_self_through(ret, &summary) {
                            ss.passthrough_self = true;
                            for f in tainted_fields_of_var("self", tainted) {
                                ss.fields.entry(f).or_default().insert(0);
                            }
                        } else if let Some(fields) = eval_struct_expr_taint(ret, tainted, &summary) {
                            for f in fields {
                                ss.fields.entry(f).or_default().insert(slot_param_idx);
                            }
                        } else if !ret_passes_self_through(ret, &summary) {
                            // Could not resolve struct fields cleanly for this seed: bail out
                            // conservatively to whole-value taint.
                            struct_sum = None;
                            non_struct_keys.insert(key.clone());
                        }
                    }
                }
            }
            if let Some(ss) = struct_sum {
                let entry = next.structs.entry(key).or_default();
                entry.passthrough_self |= ss.passthrough_self;
                for (f, idxs) in ss.fields {
                    entry.fields.entry(f).or_default().extend(idxs);
                }
            }
        }
        for k in non_struct_keys {
            next.structs.remove(&k);
        }
        if next == summary {
            break;
        }
        summary = next;
    }
    summary
}

/// A callable's direct SQL calls: their SQL argument expressions, and the
/// same as addresses for the in-flow probe.
struct SqlArgs<'a> {
    exprs: Vec<&'a Expr>,
    addrs: HashSet<usize>,
}

fn seed_flows_to_sql(
    body: &CallableBody<'_>,
    sql_args: &SqlArgs<'_>,
    seed_key: &str,
    known_local_helpers: &KnownHelpers,
    ret_taint: &LocalReturnTaint,
) -> bool {
    let mut tainted = BTreeSet::new();
    tainted.insert(seed_key.to_string());
    let mut probe = Some(FlowProbe::new(&sql_args.addrs, known_local_helpers));
    for _ in 0..8 {
        let before = tainted.len();
        let mut prop = TaintPropagator { tainted: &mut tainted, ret_taint, probe: probe.take() };
        match body {
            CallableBody::Block(b) => prop.visit_block(b),
            CallableBody::Expr(e) => prop.visit_expr(e),
        }
        probe = prop.probe.take();
        if probe.as_ref().is_some_and(|p| p.hit) {
            return true;
        }
        if tainted.len() == before {
            break;
        }
    }
    let sql_args = &sql_args.exprs;

    if sql_args.iter().any(|sql_expr| expr_uses_tainted(sql_expr, &tainted, ret_taint)) {
        return true;
    }

    if !known_local_helpers.is_empty() {
        let mut checker = LocalHelperTaintChecker {
            helpers: known_local_helpers,
            tainted: &tainted,
            ret_taint,
            aliases: BTreeMap::new(),
            hit: false,
        };
        match body {
            CallableBody::Block(b) => checker.visit_block(b),
            CallableBody::Expr(e) => checker.visit_expr(e),
        }
        if checker.hit {
            return true;
        }
    }
    false
}

/// Tuple slots tried per field when narrowing a field's SQL flow to slots.
const MAX_TRACKED_TUPLE_SLOTS: usize = 4;

fn param_sql_flow(
    body: &CallableBody<'_>,
    sql_args: &SqlArgs<'_>,
    seed_param: &str,
    known_local_helpers: &KnownHelpers,
    ret_taint: &LocalReturnTaint,
) -> Option<ParamSqlFlow> {
    if !seed_flows_to_sql(body, sql_args, seed_param, known_local_helpers, ret_taint) {
        return None;
    }
    let mut usage = ParamFieldUsageVisitor { param: seed_param, used_whole: false, fields: BTreeSet::new() };
    match body {
        CallableBody::Block(b) => usage.visit_block(b),
        CallableBody::Expr(e) => usage.visit_expr(e),
    }
    let flows = |key: &str| seed_flows_to_sql(body, sql_args, key, known_local_helpers, ret_taint);
    if !usage.used_whole && !usage.fields.is_empty() {
        let mut sql_fields = BTreeSet::new();
        for f in usage.fields {
            let field = format!("{seed_param}.{f}");
            if !flows(&field) {
                continue;
            }
            match narrow_to_tuple_slots(&field, &flows) {
                Some(slots) => sql_fields.extend(slots.into_iter().map(|k| format!("{f}.{k}"))),
                None => {
                    sql_fields.insert(f);
                }
            }
        }
        if !sql_fields.is_empty() {
            return Some(ParamSqlFlow::Fields(sql_fields));
        }
    }
    match narrow_to_tuple_slots(seed_param, &flows) {
        Some(slots) => Some(ParamSqlFlow::Fields(slots)),
        None => Some(ParamSqlFlow::Whole),
    }
}

/// A value holding tuples (`fields: &[(&str, Sql)]`, `edge.sets`) may reach SQL
/// through only some slots: `for (col, v) in fields` puts `col` in the text and
/// binds `v`. Returns those slots as `#<slot>` sub-paths when they are a strict
/// subset; `None` keeps the whole value. A whole use of the value taints every
/// slot seed, so this only narrows destructured flows.
fn narrow_to_tuple_slots(key: &str, flows: &dyn Fn(&str) -> bool) -> Option<BTreeSet<String>> {
    let slots: BTreeSet<String> = (0..MAX_TRACKED_TUPLE_SLOTS)
        .map(|k| format!("#{k}"))
        .filter(|k| flows(&format!("{key}.{k}")))
        .collect();
    (!slots.is_empty() && slots.len() < MAX_TRACKED_TUPLE_SLOTS).then_some(slots)
}

/// Every name a body mentions: path segments' last idents, method names, and
/// macro names (including inside macro bodies).
#[derive(Default)]
struct NameCollector(BTreeSet<String>);

impl<'ast> Visit<'ast> for NameCollector {
    fn visit_expr_path(&mut self, node: &'ast ExprPath) {
        if let Some(last) = node.path.segments.last() {
            self.0.insert(last.ident.to_string());
        }
        visit::visit_expr_path(self, node);
    }

    fn visit_expr_method_call(&mut self, node: &'ast ExprMethodCall) {
        self.0.insert(node.method.to_string());
        visit::visit_expr_method_call(self, node);
    }

    fn visit_macro(&mut self, node: &'ast syn::Macro) {
        if let Some(last) = node.path.segments.last() {
            self.0.insert(last.ident.to_string());
        }
        visit_macro_with(node, self);
    }
}

fn detect_sql_helpers(file: &File, ret_taint: &LocalReturnTaint) -> Vec<DetectedHelper> {
    let mut collector = CallableCollector::new();
    collector.visit_file(file);

    let mut known = KnownHelpers::new();
    let mut result: Vec<DetectedHelper> = Vec::new();
    for m in collector.macros {
        let flows = m.sql_param_indices.iter().map(|&i| (i, ParamSqlFlow::Whole)).collect();
        known.insert(m.name.clone(), (HelperKind::Macro, flows));
        result.push(m);
    }

    // Per callable, once: the SQL arguments of its direct SQL calls and every
    // name it mentions (calls, methods, macros, paths), so a round only
    // re-examines callables that can see a helper whose flows just changed.
    let facts: Vec<(SqlArgs<'_>, BTreeSet<String>)> = collector
        .callables
        .iter()
        .map(|c| {
            let mut direct = DirectSqlCollector::new();
            let mut names = NameCollector::default();
            match c.body {
                CallableBody::Block(b) => {
                    direct.visit_block(b);
                    names.visit_block(b);
                }
                CallableBody::Expr(e) => {
                    direct.visit_expr(e);
                    names.visit_expr(e);
                }
            }
            let exprs: Vec<&Expr> = direct
                .finish()
                .into_iter()
                .filter_map(|site| match site {
                    DirectSqlSite::Call(e, _) => Some(e),
                    DirectSqlSite::FnPointer(_) => None,
                })
                .collect();
            let addrs = exprs.iter().map(|e| expr_addr(e)).collect();
            (SqlArgs { exprs, addrs }, names.0)
        })
        .collect();

    let mut found_flows: BTreeMap<usize, BTreeMap<usize, ParamSqlFlow>> = BTreeMap::new();
    let mut changed_names: Option<BTreeSet<String>> = None;
    for _ in 0..4 {
        let mut next_changed = BTreeSet::new();
        for (idx, c) in collector.callables.iter().enumerate() {
            let (sql_args, names) = &facts[idx];
            let sees_helper = |n: &String| known.contains_key(n);
            let relevant = match &changed_names {
                // First round: anything with a SQL call or a call to a macro helper.
                None => !sql_args.exprs.is_empty() || names.iter().any(sees_helper),
                Some(changed) => names.iter().any(|n| changed.contains(n)),
            };
            if !relevant {
                continue;
            }
            let mut sql_flows: BTreeMap<usize, ParamSqlFlow> = BTreeMap::new();
            for (p_idx, p_name) in &c.params {
                if let Some(flow) = param_sql_flow(&c.body, sql_args, p_name, &known, ret_taint) {
                    sql_flows.insert(*p_idx, flow);
                }
            }
            if !sql_flows.is_empty() {
                let entry = found_flows.entry(idx).or_default();
                let before = entry.clone();
                for (p_idx, flow) in sql_flows {
                    entry.entry(p_idx).and_modify(|e| e.merge(flow.clone())).or_insert(flow.clone());
                    let k_entry = known.entry(c.name.clone()).or_insert_with(|| (c.kind, BTreeMap::new()));
                    k_entry.1.entry(p_idx).and_modify(|e| e.merge(flow.clone())).or_insert(flow);
                }
                if *entry != before {
                    next_changed.insert(c.name.clone());
                }
            }
        }
        if next_changed.is_empty() {
            break;
        }
        changed_names = Some(next_changed);
    }

    for (idx, sql_flows) in found_flows {
        let c = &collector.callables[idx];
        result.push(DetectedHelper {
            name: c.name.clone(),
            vis: c.vis,
            kind: c.kind,
            is_pub: c.is_pub,
            line: c.line,
            sql_param_indices: sql_flows.into_keys().collect(),
        });
    }
    result
}

// ---------------------------------------------------------------------------
// Counting calls (including fn-pointer aliases & macro invocations) to helpers
// ---------------------------------------------------------------------------

struct HelperCallCounter<'a> {
    helpers: &'a BTreeMap<String, BTreeSet<HelperKind>>,
    /// Counted call sites: `(line, helper name)`.
    sites: Vec<(usize, String)>,
    /// Local fn-pointer alias `let g = run_sql;` -> `(helper_name, called)`.
    aliases: BTreeMap<String, (String, bool, usize)>,
    /// Scoped local variable / parameter names in the current block so a local
    /// variable named `count` or `ids` is never mistaken for a bare fn-pointer
    /// reference to a helper of the same name.
    local_vars: Vec<BTreeSet<String>>,
    skip_direct_path: bool,
}

impl<'a> HelperCallCounter<'a> {
    fn new(helpers: &'a BTreeMap<String, BTreeSet<HelperKind>>) -> Self {
        Self {
            helpers,
            sites: Vec::new(),
            aliases: BTreeMap::new(),
            local_vars: vec![BTreeSet::new()],
            skip_direct_path: false,
        }
    }

    fn push_scope(&mut self) {
        self.local_vars.push(BTreeSet::new());
    }

    fn pop_scope(&mut self) {
        self.local_vars.pop();
    }

    fn bind_pat(&mut self, pat: &Pat) {
        let mut names = Vec::new();
        collect_pat_idents(pat, &mut names);
        if let Some(scope) = self.local_vars.last_mut() {
            scope.extend(names);
        }
    }

    fn is_shadowed_by_local(&self, name: &str) -> bool {
        self.local_vars.iter().any(|s| s.contains(name))
    }

    fn finish(mut self) -> Vec<(usize, String)> {
        for (_, (target, called, line)) in self.aliases {
            if !called {
                self.sites.push((line, format!("{target} (fn pointer)")));
            }
        }
        self.sites
    }

    fn matches_kind(&self, name: &str, kind: HelperKind) -> bool {
        self.helpers.get(name).is_some_and(|ks| ks.contains(&kind))
    }

    fn has_fn_or_closure(&self, name: &str) -> bool {
        self.matches_kind(name, HelperKind::Fn) || self.matches_kind(name, HelperKind::Closure)
    }
}

impl<'ast> Visit<'ast> for HelperCallCounter<'_> {
    fn visit_item(&mut self, node: &'ast Item) {
        if item_has_cfg_test(node) {
            return;
        }
        if let Item::Macro(im) = node {
            if im.mac.path.is_ident("macro_rules") {
                return;
            }
            if let Some(last) = im.mac.path.segments.last()
                && self.matches_kind(&last.ident.to_string(), HelperKind::Macro)
            {
                self.sites.push((last.ident.span().start().line, format!("{}!", last.ident)));
            }
            visit_macro_with(&im.mac, self);
            return;
        }
        visit::visit_item(self, node);
    }

    fn visit_impl_item(&mut self, node: &'ast syn::ImplItem) {
        if impl_item_has_cfg_test(node) {
            return;
        }
        visit::visit_impl_item(self, node);
    }

    fn visit_trait_item(&mut self, node: &'ast syn::TraitItem) {
        if trait_item_has_cfg_test(node) {
            return;
        }
        visit::visit_trait_item(self, node);
    }

    fn visit_item_fn(&mut self, node: &'ast ItemFn) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        self.push_scope();
        for arg in &node.sig.inputs {
            if let FnArg::Typed(pt) = arg {
                self.bind_pat(&pt.pat);
            }
        }
        visit::visit_block(self, &node.block);
        self.pop_scope();
    }

    fn visit_impl_item_fn(&mut self, node: &'ast ImplItemFn) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        self.push_scope();
        for arg in &node.sig.inputs {
            if let FnArg::Typed(pt) = arg {
                self.bind_pat(&pt.pat);
            }
        }
        visit::visit_block(self, &node.block);
        self.pop_scope();
    }

    fn visit_trait_item_fn(&mut self, node: &'ast TraitItemFn) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        if let Some(body) = &node.default {
            self.push_scope();
            for arg in &node.sig.inputs {
                if let FnArg::Typed(pt) = arg {
                    self.bind_pat(&pt.pat);
                }
            }
            visit::visit_block(self, body);
            self.pop_scope();
        }
    }

    fn visit_block(&mut self, node: &'ast syn::Block) {
        self.push_scope();
        visit::visit_block(self, node);
        self.pop_scope();
    }

    fn visit_expr_closure(&mut self, node: &'ast ExprClosure) {
        self.push_scope();
        for pat in &node.inputs {
            self.bind_pat(pat);
        }
        visit::visit_expr(self, &node.body);
        self.pop_scope();
    }

    fn visit_expr_for_loop(&mut self, node: &'ast ExprForLoop) {
        self.visit_expr(&node.expr);
        self.push_scope();
        self.bind_pat(&node.pat);
        self.visit_block(&node.body);
        self.pop_scope();
    }

    fn visit_arm(&mut self, node: &'ast syn::Arm) {
        self.push_scope();
        self.bind_pat(&node.pat);
        if let Some((_, guard)) = &node.guard {
            self.visit_expr(guard);
        }
        self.visit_expr(&node.body);
        self.pop_scope();
    }

    fn visit_expr_if(&mut self, node: &'ast ExprIf) {
        self.push_scope();
        self.visit_expr(&node.cond);
        if let Expr::Let(el) = &*node.cond {
            self.bind_pat(&el.pat);
        }
        self.visit_block(&node.then_branch);
        self.pop_scope();
        if let Some((_, eb)) = &node.else_branch {
            self.visit_expr(eb);
        }
    }

    fn visit_expr_while(&mut self, node: &'ast ExprWhile) {
        self.push_scope();
        self.visit_expr(&node.cond);
        if let Expr::Let(el) = &*node.cond {
            self.bind_pat(&el.pat);
        }
        self.visit_block(&node.body);
        self.pop_scope();
    }

    fn visit_local(&mut self, node: &'ast Local) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        if let Some(init) = &node.init
            && let Expr::Path(ep) = unwrap_ref_or_cast(&init.expr)
            && ep.qself.is_none()
            && let Some(last) = ep.path.segments.last()
        {
            let target = last.ident.to_string();
            let is_callable_helper = (ep.path.segments.len() == 1
                && self.has_fn_or_closure(&target)
                && !self.is_shadowed_by_local(&target))
                || (ep.path.segments.len() >= 2
                    && (self.has_fn_or_closure(&target) || self.matches_kind(&target, HelperKind::Method)));
            if is_callable_helper {
                let mut vars = Vec::new();
                collect_pat_idents(&node.pat, &mut vars);
                if !vars.is_empty() {
                    for v in vars {
                        self.aliases.insert(v, (target.clone(), false, ep.span().start().line));
                    }
                    if let Some((_, diverge)) = &init.diverge {
                        self.visit_expr(diverge);
                    }
                    return;
                }
            }
        }
        visit::visit_local(self, node);
        // Bind non-closure locals AFTER visiting init so `let count = count(c, ...)`
        // still sees the helper `count` in its own initializer, while subsequent
        // uses of `count` are shadowed as a local variable (not a fn pointer!).
        let is_closure_init =
            node.init.as_ref().is_some_and(|init| matches!(unwrap_parens(&init.expr), Expr::Closure(_)));
        if !is_closure_init {
            self.bind_pat(&node.pat);
        }
    }

    fn visit_stmt(&mut self, node: &'ast Stmt) {
        if stmt_has_cfg_test(node) {
            return;
        }
        if let Stmt::Macro(sm) = node {
            if let Some(last) = sm.mac.path.segments.last()
                && self.matches_kind(&last.ident.to_string(), HelperKind::Macro)
            {
                self.sites.push((last.ident.span().start().line, format!("{}!", last.ident)));
            }
            visit_macro_with(&sm.mac, self);
            return;
        }
        visit::visit_stmt(self, node);
    }

    fn visit_expr_macro(&mut self, node: &'ast ExprMacro) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        if let Some(last) = node.mac.path.segments.last()
            && self.matches_kind(&last.ident.to_string(), HelperKind::Macro)
        {
            self.sites.push((last.ident.span().start().line, format!("{}!", last.ident)));
        }
        visit_macro_with(&node.mac, self);
    }

    fn visit_expr_method_call(&mut self, node: &'ast ExprMethodCall) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        if self.matches_kind(&node.method.to_string(), HelperKind::Method) {
            self.sites.push((node.method.span().start().line, format!(".{}", node.method)));
        }
        visit::visit_expr_method_call(self, node);
    }

    fn visit_expr_call(&mut self, node: &'ast ExprCall) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        let inner = unwrap_parens(&node.func);
        let mut matched = false;
        if let Expr::Path(ep) = inner
            && ep.qself.is_none()
            && let Some(last) = ep.path.segments.last()
        {
            let name = last.ident.to_string();
            if ep.path.segments.len() == 1
                && let Some((target, called, _)) = self.aliases.get_mut(&name)
            {
                *called = true;
                self.sites.push((last.ident.span().start().line, format!("{target} (via {name})")));
                matched = true;
            } else if (ep.path.segments.len() == 1
                && self.has_fn_or_closure(&name)
                && !self.is_shadowed_by_local(&name))
                || (ep.path.segments.len() >= 2
                    && (self.has_fn_or_closure(&name) || self.matches_kind(&name, HelperKind::Method)))
            {
                self.sites.push((last.ident.span().start().line, name.clone()));
                matched = true;
            }
        }
        // A called path is never a fn-pointer reference.
        let prev = self.skip_direct_path;
        self.skip_direct_path = matched || matches!(inner, Expr::Path(_));
        self.visit_expr(&node.func);
        self.skip_direct_path = prev;
        for arg in &node.args {
            self.visit_expr(arg);
        }
    }

    fn visit_expr_path(&mut self, node: &'ast ExprPath) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        if !self.skip_direct_path
            && node.qself.is_none()
            && let Some(last) = node.path.segments.last()
        {
            let name = last.ident.to_string();
            // Count a bare fn-pointer reference to an in-scope helper (e.g. `apply(run_sql)` or
            // `items.map(crate::helpers::run_sql)`). Only count multi-segment paths for methods,
            // or non-shadowed paths for Fn/Closure.
            let is_helper_ref = if node.path.segments.len() >= 2 {
                self.has_fn_or_closure(&name) || self.matches_kind(&name, HelperKind::Method)
            } else {
                self.has_fn_or_closure(&name)
                    && !self.aliases.contains_key(&name)
                    && !self.is_shadowed_by_local(&name)
            };
            if is_helper_ref {
                self.sites.push((last.ident.span().start().line, format!("{name} (fn pointer)")));
            }
        }
        visit::visit_expr_path(self, node);
    }
}

