fn cfg_tokens_require_test(tokens: TokenStream) -> bool {
    let items: Vec<TokenTree> = tokens.into_iter().collect();
    if items.len() == 1
        && let TokenTree::Ident(id) = &items[0]
        && id == "test"
    {
        return true;
    }
    if items.len() >= 2
        && let TokenTree::Ident(id) = &items[0]
        && id == "all"
        && let TokenTree::Group(g) = &items[1]
        && g.delimiter() == Delimiter::Parenthesis
    {
        return split_tt_commas(g.stream()).into_iter().any(cfg_tokens_require_test);
    }
    false
}

fn split_tt_commas(stream: TokenStream) -> Vec<TokenStream> {
    let mut out = Vec::new();
    let mut cur = Vec::new();
    for tt in stream {
        if let TokenTree::Punct(p) = &tt
            && p.as_char() == ','
        {
            if !cur.is_empty() {
                out.push(cur.drain(..).collect());
            }
            continue;
        }
        cur.push(tt);
    }
    if !cur.is_empty() {
        out.push(cur.into_iter().collect());
    }
    out
}

fn attr_is_cfg_test(attr: &Attribute) -> bool {
    if !attr.path().is_ident("cfg") {
        return false;
    }
    match &attr.meta {
        syn::Meta::List(list) => cfg_tokens_require_test(list.tokens.clone()),
        _ => false,
    }
}

fn attrs_have_cfg_test(attrs: &[Attribute]) -> bool {
    attrs.iter().any(attr_is_cfg_test)
}

fn attrs_have_inner_cfg_test(attrs: &[Attribute]) -> bool {
    attrs.iter().any(|a| matches!(a.style, AttrStyle::Inner(_)) && attr_is_cfg_test(a))
}

fn attrs_have_macro_export(attrs: &[Attribute]) -> bool {
    attrs.iter().any(|a| a.path().is_ident("macro_export"))
}

fn attr_path_value(attrs: &[Attribute]) -> Option<String> {
    for attr in attrs {
        if attr.path().is_ident("path")
            && let syn::Meta::NameValue(nv) = &attr.meta
            && let Expr::Lit(lit) = &nv.value
            && let syn::Lit::Str(s) = &lit.lit
        {
            return Some(s.value());
        }
    }
    None
}

/// Discover out-of-line `#[cfg(test)] mod <name>;` (and `#[path = "..."]`)
/// targets declared anywhere in `file`, plus inner `#![cfg(test)]` files.
struct TestModFinder<'a> {
    file_path: &'a Path,
    excluded_files: &'a mut BTreeSet<PathBuf>,
    excluded_dirs: &'a mut BTreeSet<PathBuf>,
}

impl<'ast> Visit<'ast> for TestModFinder<'_> {
    fn visit_item_mod(&mut self, node: &'ast ItemMod) {
        if node.content.is_none() && attrs_have_cfg_test(&node.attrs) {
            let parent_dir = self.file_path.parent().unwrap_or_else(|| Path::new(""));
            let stem = self.file_path.file_stem().and_then(|s| s.to_str()).unwrap_or("");
            let is_mod_root = matches!(stem, "lib" | "main" | "mod");
            let mod_name = node.ident.to_string();
            let path_override = attr_path_value(&node.attrs);

            let mut candidates = Vec::new();
            if let Some(rel) = path_override {
                candidates.push(parent_dir.join(&rel));
                if !is_mod_root {
                    candidates.push(parent_dir.join(stem).join(&rel));
                }
            } else if is_mod_root {
                candidates.push(parent_dir.join(format!("{mod_name}.rs")));
                candidates.push(parent_dir.join(&mod_name).join("mod.rs"));
            } else {
                candidates.push(parent_dir.join(stem).join(format!("{mod_name}.rs")));
                candidates.push(parent_dir.join(stem).join(&mod_name).join("mod.rs"));
                candidates.push(parent_dir.join(format!("{mod_name}.rs")));
            }
            for cand in candidates {
                if let Ok(canon) = std::fs::canonicalize(&cand) {
                    if canon.file_name().and_then(|n| n.to_str()) == Some("mod.rs")
                        && let Some(dir) = canon.parent()
                    {
                        self.excluded_dirs.insert(dir.to_path_buf());
                    }
                    self.excluded_files.insert(canon);
                }
            }
            return;
        }
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        visit::visit_item_mod(self, node);
    }
}

