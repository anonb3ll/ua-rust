#[test]
fn self_test_two_way_drift_reporting() {
    let baseline = &[("ua-tools", "src/a.rs", 5), ("ua-tools", "src/b.rs", 3)];

    let mut exact = BTreeMap::new();
    exact.insert(("ua-tools".into(), "src/a.rs".into()), 5);
    exact.insert(("ua-tools".into(), "src/b.rs".into()), 3);
    assert!(check_counts_baseline("SQL_BASELINE", &exact, baseline).is_ok());

    let mut higher = exact.clone();
    higher.insert(("ua-tools".into(), "src/a.rs".into()), 6);
    let err = check_counts_baseline("SQL_BASELINE", &higher, baseline).unwrap_err();
    assert!(err.contains("Above baseline") && err.contains("got 6, baseline 5"), "{err}");

    let mut lower = exact.clone();
    lower.insert(("ua-tools".into(), "src/b.rs".into()), 1);
    let err = check_counts_baseline("SQL_BASELINE", &lower, baseline).unwrap_err();
    assert!(err.contains("Below baseline") && err.contains("got 1, baseline 3"), "{err}");

    let mut new_file = exact;
    new_file.insert(("ua-tools".into(), "src/new.rs".into()), 1);
    let err = check_counts_baseline("SQL_BASELINE", &new_file, baseline).unwrap_err();
    assert!(err.contains("ua-tools/src/new.rs: got 1, baseline 0"), "{err}");
}
