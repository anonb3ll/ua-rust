/// Expected argument count in method-call form (`.method(...)`) for each
/// `rusqlite::Connection` / `Transaction` SQL-taking method. Distinguishes
/// `Connection::execute(sql, params)` (2 args) and `Connection::query_row(sql, params, f)`
/// (3 args) from already-prepared `Statement::execute(params)` (1 arg) and
/// `Statement::query_row(params, f)` (2 args).
fn expected_sql_method_args(method: &str) -> Option<usize> {
    match method {
        "prepare" | "prepare_cached" | "execute_batch" => Some(1),
        "prepare_with_flags" | "execute" => Some(2),
        "query_row" | "query_row_and_then" | "query_one" => Some(3),
        _ => None,
    }
}

/// Match a UFCS path like `Connection::execute`, `rusqlite::Transaction::query_row`,
/// `WriteTx::prepare`, or `Batch::new`. Returns `(expected_call_arity, sql_arg_index)`.
fn ufcs_sql_path_signature(path: &syn::Path) -> Option<(usize, usize)> {
    let segs: Vec<String> = path.segments.iter().map(|s| s.ident.to_string()).collect();
    if segs.len() < 2 {
        return None;
    }
    let last = segs.last()?.as_str();
    let prev = segs[segs.len() - 2].as_str();
    if prev == "Batch" && last == "new" {
        return Some((2, 1));
    }
    if let Some(expected) = expected_sql_method_args(last) {
        return Some((expected + 1, 1));
    }
    None
}

/// Stricter check for bare fn-pointer paths (not immediately invoked in `path(...)`):
/// avoids matching unrelated `SomeService::execute` fn pointers while catching
/// `Connection::execute`, `Transaction::query_row`, `WriteTx::prepare`,
/// `Savepoint::execute_batch`, `Batch::new`, or anything under `rusqlite::`.
fn is_sql_fn_pointer_path(path: &syn::Path) -> Option<(usize, usize)> {
    ufcs_sql_path_signature(path)
}

fn unwrap_parens(mut expr: &Expr) -> &Expr {
    loop {
        match expr {
            Expr::Paren(p) => expr = &p.expr,
            Expr::Group(g) => expr = &g.expr,
            _ => return expr,
        }
    }
}

fn unwrap_ref_or_cast(mut expr: &Expr) -> &Expr {
    loop {
        match expr {
            Expr::Paren(p) => expr = &p.expr,
            Expr::Group(g) => expr = &g.expr,
            Expr::Cast(c) => expr = &c.expr,
            Expr::Reference(r) => expr = &r.expr,
            _ => return expr,
        }
    }
}

fn collect_pat_idents(pat: &Pat, out: &mut Vec<String>) {
    match pat {
        Pat::Ident(pi) => {
            let name = pi.ident.to_string();
            if name != "_" {
                out.push(name);
            }
            if let Some((_, sub)) = &pi.subpat {
                collect_pat_idents(sub, out);
            }
        }
        Pat::Tuple(pt) => {
            for p in &pt.elems {
                collect_pat_idents(p, out);
            }
        }
        Pat::TupleStruct(pts) => {
            for p in &pts.elems {
                collect_pat_idents(p, out);
            }
        }
        Pat::Struct(ps) => {
            for f in &ps.fields {
                collect_pat_idents(&f.pat, out);
            }
        }
        Pat::Reference(pr) => collect_pat_idents(&pr.pat, out),
        Pat::Type(pt) => collect_pat_idents(&pt.pat, out),
        Pat::Slice(ps) => {
            for p in &ps.elems {
                collect_pat_idents(p, out);
            }
        }
        Pat::Paren(pp) => collect_pat_idents(&pp.pat, out),
        Pat::Or(po) => {
            for p in &po.cases {
                collect_pat_idents(p, out);
            }
        }
        _ => {}
    }
}

/// Extract a dotted place key for a local place expression (`x`, `s.values`,
/// `s.a.b`), ignoring borrows/derefs/parens.
fn place_key_of_expr(expr: &Expr) -> Option<String> {
    match unwrap_parens(expr) {
        Expr::Path(ep) if ep.qself.is_none() && ep.path.segments.len() == 1 => {
            Some(ep.path.segments[0].ident.to_string())
        }
        Expr::Field(f) => {
            let base = place_key_of_expr(&f.base)?;
            let member = match &f.member {
                syn::Member::Named(id) => id.to_string(),
                syn::Member::Unnamed(idx) => idx.index.to_string(),
            };
            Some(format!("{base}.{member}"))
        }
        Expr::Unary(u) => place_key_of_expr(&u.expr),
        Expr::Reference(r) => place_key_of_expr(&r.expr),
        Expr::Index(idx) => place_key_of_expr(&idx.expr),
        _ => None,
    }
}

/// Extract the root identifier of a place expression (`x`, `x.foo`, `*x`, `&mut x`).
fn root_ident_of_expr(expr: &Expr) -> Option<String> {
    match unwrap_parens(expr) {
        Expr::Path(ep) if ep.qself.is_none() && ep.path.segments.len() == 1 => {
            Some(ep.path.segments[0].ident.to_string())
        }
        Expr::Field(f) => root_ident_of_expr(&f.base),
        Expr::Unary(u) => root_ident_of_expr(&u.expr),
        Expr::Reference(r) => root_ident_of_expr(&r.expr),
        Expr::Index(idx) => root_ident_of_expr(&idx.expr),
        _ => None,
    }
}

/// One detected direct SQL call or bare fn-pointer reference.
#[derive(Clone)]
enum DirectSqlSite<'ast> {
    /// Call site carrying its parsed SQL argument expression.
    Call(&'ast Expr, usize),
    /// Bare SQL fn-pointer reference (e.g. `apply(Connection::execute, ...)` or uncalled alias).
    FnPointer(usize),
}

/// Walk an AST node collecting direct SQL calls (method, UFCS, `Batch::new`,
/// local fn-pointer aliases, and bare fn-pointer references), skipping
/// `#[cfg(test)]` / `#![cfg(test)]` items and recursing into macro invocations.
struct DirectSqlCollector<'ast> {
    sites: Vec<DirectSqlSite<'ast>>,
    /// Local fn-pointer aliases (`let f = Connection::execute;`) -> (arity, sql_idx, called).
    aliases: BTreeMap<String, (usize, usize, bool, usize)>,
    /// Suppress bare fn-pointer counting while visiting an already-handled call func or alias RHS.
    skip_direct_path: bool,
}

impl<'ast> DirectSqlCollector<'ast> {
    fn new() -> Self {
        Self { sites: Vec::new(), aliases: BTreeMap::new(), skip_direct_path: false }
    }

    fn finish(mut self) -> Vec<DirectSqlSite<'ast>> {
        for (_, (_, _, called, line)) in self.aliases {
            if !called {
                self.sites.push(DirectSqlSite::FnPointer(line));
            }
        }
        self.sites
    }

    fn record_alias_binding(&mut self, pat: &Pat, init: &Expr) -> bool {
        if let Expr::Path(ep) = unwrap_ref_or_cast(init)
            && ep.qself.is_none()
            && let Some((arity, sql_idx)) = is_sql_fn_pointer_path(&ep.path)
        {
            let mut names = Vec::new();
            collect_pat_idents(pat, &mut names);
            if !names.is_empty() {
                for n in names {
                    self.aliases.insert(n, (arity, sql_idx, false, ep.span().start().line));
                }
                return true;
            }
        }
        false
    }

    fn visit_macro_stream(&mut self, mac: &syn::Macro) {
        // Do not parse `macro_rules!` definitions as direct SQL calls here;
        // `macro_rules!` wrappers are detected and counted at invocation sites.
        if mac.path.is_ident("macro_rules") {
            return;
        }
        visit_macro_with(mac, self);
    }
}

impl<'ast> Visit<'ast> for DirectSqlCollector<'ast> {
    fn visit_item(&mut self, node: &'ast Item) {
        if item_has_cfg_test(node) {
            return;
        }
        if let Item::Macro(im) = node {
            if !im.mac.path.is_ident("macro_rules") {
                self.visit_macro_stream(&im.mac);
            }
            return;
        }
        if let Item::Const(ItemConst { ident, expr, .. }) | Item::Static(ItemStatic { ident, expr, .. }) =
            node
            && let Expr::Path(ep) = unwrap_ref_or_cast(expr)
            && ep.qself.is_none()
            && let Some((arity, sql_idx)) = is_sql_fn_pointer_path(&ep.path)
        {
            self.aliases.insert(ident.to_string(), (arity, sql_idx, false, ident.span().start().line));
            return;
        }
        visit::visit_item(self, node);
    }

    fn visit_impl_item(&mut self, node: &'ast syn::ImplItem) {
        if impl_item_has_cfg_test(node) {
            return;
        }
        visit::visit_impl_item(self, node);
    }

    fn visit_trait_item(&mut self, node: &'ast syn::TraitItem) {
        if trait_item_has_cfg_test(node) {
            return;
        }
        visit::visit_trait_item(self, node);
    }

    fn visit_local(&mut self, node: &'ast Local) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        if let Some(init) = &node.init
            && self.record_alias_binding(&node.pat, &init.expr)
        {
            if let Some((_, diverge)) = &init.diverge {
                self.visit_expr(diverge);
            }
            return;
        }
        visit::visit_local(self, node);
    }

    fn visit_stmt(&mut self, node: &'ast Stmt) {
        if stmt_has_cfg_test(node) {
            return;
        }
        if let Stmt::Macro(sm) = node {
            self.visit_macro_stream(&sm.mac);
            return;
        }
        visit::visit_stmt(self, node);
    }

    fn visit_expr_macro(&mut self, node: &'ast ExprMacro) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        self.visit_macro_stream(&node.mac);
    }

    fn visit_expr_method_call(&mut self, node: &'ast ExprMethodCall) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        let method = node.method.to_string();
        if let Some(expected) = expected_sql_method_args(&method)
            && node.args.len() == expected
        {
            self.sites.push(DirectSqlSite::Call(&node.args[0], node.method.span().start().line));
        }
        visit::visit_expr_method_call(self, node);
    }

    fn visit_expr_call(&mut self, node: &'ast ExprCall) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        let inner_func = unwrap_parens(&node.func);
        let mut handled_func = false;
        if let Expr::Path(ep) = inner_func
            && ep.qself.is_none()
        {
            if let Some((expected_arity, sql_idx)) = ufcs_sql_path_signature(&ep.path) {
                if node.args.len() == expected_arity {
                    self.sites.push(DirectSqlSite::Call(&node.args[sql_idx], ep.span().start().line));
                    handled_func = true;
                }
            } else if ep.path.segments.len() == 1 {
                let name = ep.path.segments[0].ident.to_string();
                if let Some((expected_arity, sql_idx, called, _)) = self.aliases.get_mut(&name)
                    && node.args.len() == *expected_arity
                {
                    *called = true;
                    self.sites.push(DirectSqlSite::Call(&node.args[*sql_idx], ep.span().start().line));
                    handled_func = true;
                }
            }
        }
        // A called path (`engine::execute(a, b, c, d)` with a non-SQL arity) is
        // not a fn-pointer value; only a path used as a value is.
        let prev = self.skip_direct_path;
        self.skip_direct_path = handled_func || matches!(inner_func, Expr::Path(_));
        self.visit_expr(&node.func);
        self.skip_direct_path = prev;
        for arg in &node.args {
            self.visit_expr(arg);
        }
    }

    fn visit_expr_path(&mut self, node: &'ast ExprPath) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        if !self.skip_direct_path && node.qself.is_none() && is_sql_fn_pointer_path(&node.path).is_some() {
            self.sites.push(DirectSqlSite::FnPointer(node.span().start().line));
        }
        visit::visit_expr_path(self, node);
    }
}

fn parse_comma_exprs(tokens: TokenStream) -> syn::Result<Punctuated<Expr, Token![,]>> {
    syn::parse::Parser::parse2(Punctuated::<Expr, Token![,]>::parse_terminated, tokens)
}

/// One parsed piece of a macro invocation body, in source order.
enum MacroPiece {
    Expr(Expr),
    Block(syn::Block),
}

/// A macro invocation's token stream parsed once per scan (see `macro_parse`).
struct MacroParse {
    /// Comma-separated arguments, when the body parses that way.
    args: Option<Punctuated<Expr, Token![,]>>,
    /// `vec![...]` body re-parsed as an array or repeat expression.
    vec_expr: Option<Expr>,
    /// `{ident}` captures from string literals of `format!`-family macros.
    fmt_captures: Vec<String>,
    /// Best-effort decomposition used to visit nested calls (handles
    /// `vec![...]`, `dbg!(...)`, `tokio::select! { ... }`, `json!({ ... })`, etc.).
    pieces: Vec<MacroPiece>,
}

thread_local! {
    /// Macro address -> parse, installed by `analyze` for one scan. Parses are
    /// leaked so nested macros inside them keep stable addresses; scanned file
    /// ASTs outlive the scan, so no key is reused while the cache is installed.
    static MACRO_CACHE: RefCell<Option<HashMap<usize, &'static MacroParse>>> = const { RefCell::new(None) };
}

struct MacroCacheGuard;

impl MacroCacheGuard {
    fn install() -> Self {
        MACRO_CACHE.with(|c| *c.borrow_mut() = Some(HashMap::new()));
        MacroCacheGuard
    }
}

impl Drop for MacroCacheGuard {
    fn drop(&mut self) {
        MACRO_CACHE.with(|c| *c.borrow_mut() = None);
    }
}

fn macro_parse(mac: &syn::Macro) -> &'static MacroParse {
    let key = mac as *const syn::Macro as usize;
    if let Some(hit) = MACRO_CACHE.with(|c| c.borrow().as_ref().and_then(|m| m.get(&key).copied())) {
        return hit;
    }
    let parsed: &'static MacroParse = Box::leak(Box::new(build_macro_parse(mac)));
    MACRO_CACHE.with(|c| {
        if let Some(m) = c.borrow_mut().as_mut() {
            m.insert(key, parsed);
        }
    });
    parsed
}

fn build_macro_parse(mac: &syn::Macro) -> MacroParse {
    let last_name = mac.path.segments.last().map(|s| s.ident.to_string()).unwrap_or_default();
    let vec_expr =
        if last_name == "vec" { syn::parse2::<Expr>(quote_brackets(mac.tokens.clone())).ok() } else { None };
    let mut fmt_captures = Vec::new();
    if matches!(last_name.as_str(), "format" | "write" | "writeln" | "concat") {
        for tt in mac.tokens.clone() {
            if let TokenTree::Literal(_) = &tt
                && let Ok(syn::Lit::Str(s)) = syn::parse2::<syn::Lit>(TokenStream::from(tt))
            {
                fmt_captures.extend(format_captures(&s.value()));
            }
        }
    }
    let mut pieces = Vec::new();
    decompose_macro_tokens(mac.tokens.clone(), &mut pieces);
    MacroParse { args: parse_comma_exprs(mac.tokens.clone()).ok(), vec_expr, fmt_captures, pieces }
}

fn decompose_macro_tokens(tokens: TokenStream, out: &mut Vec<MacroPiece>) {
    if tokens.is_empty() {
        return;
    }
    if let Ok(expr) = syn::parse2::<Expr>(tokens.clone()) {
        out.push(MacroPiece::Expr(expr));
        return;
    }
    if let Ok(exprs) = parse_comma_exprs(tokens.clone()) {
        out.extend(exprs.into_iter().map(MacroPiece::Expr));
        return;
    }
    if let Ok(block) = syn::parse2::<syn::Block>(quote_braces(tokens.clone())) {
        out.push(MacroPiece::Block(block));
        return;
    }
    // Split on top-level `,` or `;` or `=>` or `:` segments and try parsing each as an Expr,
    // recursing into nested groups.
    for seg in split_macro_segments(tokens) {
        if let Ok(expr) = syn::parse2::<Expr>(seg.clone()) {
            out.push(MacroPiece::Expr(expr));
        } else {
            for tt in seg {
                if let TokenTree::Group(g) = tt {
                    decompose_macro_tokens(g.stream(), out);
                }
            }
        }
    }
}

/// Visit the parsed pieces of a macro invocation's body.
fn visit_macro_with<'ast, V: Visit<'ast>>(mac: &syn::Macro, visitor: &mut V) {
    for piece in &macro_parse(mac).pieces {
        match piece {
            MacroPiece::Expr(e) => visitor.visit_expr(e),
            MacroPiece::Block(b) => visitor.visit_block(b),
        }
    }
}

fn quote_braces(inner: TokenStream) -> TokenStream {
    TokenStream::from(TokenTree::Group(proc_macro2::Group::new(Delimiter::Brace, inner)))
}

fn split_macro_segments(stream: TokenStream) -> Vec<TokenStream> {
    let tts: Vec<TokenTree> = stream.into_iter().collect();
    let mut out = Vec::new();
    let mut cur = Vec::new();
    let mut i = 0;
    while i < tts.len() {
        if let TokenTree::Punct(p) = &tts[i] {
            if matches!(p.as_char(), ',' | ';') {
                if !cur.is_empty() {
                    out.push(cur.drain(..).collect());
                }
                i += 1;
                continue;
            }
            if p.as_char() == '='
                && p.spacing() == Spacing::Joint
                && let Some(TokenTree::Punct(p2)) = tts.get(i + 1)
                && p2.as_char() == '>'
            {
                if !cur.is_empty() {
                    out.push(cur.drain(..).collect());
                }
                i += 2;
                continue;
            }
            if p.as_char() == ':'
                && p.spacing() == Spacing::Alone
                && !(i > 0 && matches!(&tts[i - 1], TokenTree::Punct(prev) if prev.as_char() == ':'))
            {
                if !cur.is_empty() {
                    out.push(cur.drain(..).collect());
                }
                i += 1;
                continue;
            }
        }
        cur.push(tts[i].clone());
        i += 1;
    }
    if !cur.is_empty() {
        out.push(cur.into_iter().collect());
    }
    out
}

