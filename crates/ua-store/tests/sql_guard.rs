struct ScannedFile {
    krate: String,
    rel: String,
    dir: PathBuf,
    ast: File,
}

fn rust_files_under(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else { return };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            rust_files_under(&path, out);
        } else if path.extension().is_some_and(|e| e == "rs") {
            out.push(path);
        }
    }
}

fn scan_workspace() -> Vec<ScannedFile> {
    let crates_dir = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap();
    scan_crates_dir(crates_dir)
}

fn scan_crates_dir(crates_dir: &Path) -> Vec<ScannedFile> {
    let mut raw_files: Vec<(String, String, PathBuf, String)> = Vec::new();
    let mut crate_dirs: Vec<PathBuf> = std::fs::read_dir(crates_dir)
        .unwrap()
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.join("src").is_dir())
        .collect();
    crate_dirs.sort();

    for cdir in crate_dirs {
        let krate = cdir.file_name().unwrap().to_string_lossy().into_owned();
        let src_dir = cdir.join("src");
        let mut files = Vec::new();
        rust_files_under(&src_dir, &mut files);
        files.sort();
        for f in files {
            let rel = f.strip_prefix(&cdir).unwrap().to_string_lossy().replace('\\', "/");
            let text = std::fs::read_to_string(&f).unwrap();
            raw_files.push((krate.clone(), rel, f, text));
        }
    }

    // Pass 1: parse every file with `syn` and discover every out-of-line
    // `#[cfg(test)] mod ...;` target and inner `#![cfg(test)]` file/dir.
    let mut excluded_files = BTreeSet::new();
    let mut excluded_dirs = BTreeSet::new();
    let mut parsed: Vec<(String, String, PathBuf, File)> = Vec::with_capacity(raw_files.len());
    for (krate, rel, path, text) in raw_files {
        let ast = syn::parse_file(&text).unwrap_or_else(|e| panic!("syn failed to parse {krate}/{rel}: {e}"));
        if attrs_have_inner_cfg_test(&ast.attrs) {
            if let Ok(canon) = std::fs::canonicalize(&path) {
                if canon.file_name().and_then(|n| n.to_str()) == Some("mod.rs")
                    && let Some(dir) = canon.parent()
                {
                    excluded_dirs.insert(dir.to_path_buf());
                }
                excluded_files.insert(canon);
            }
            continue;
        }
        let mut finder = TestModFinder {
            file_path: &path,
            excluded_files: &mut excluded_files,
            excluded_dirs: &mut excluded_dirs,
        };
        finder.visit_file(&ast);
        parsed.push((krate, rel, path, ast));
    }

    // Pass 2: drop excluded test files and directories.
    let mut out = Vec::new();
    for (krate, rel, path, ast) in parsed {
        if let Ok(canon) = std::fs::canonicalize(&path)
            && (excluded_files.contains(&canon) || excluded_dirs.iter().any(|d| canon.starts_with(d)))
        {
            continue;
        }
        let dir = path.parent().unwrap_or_else(|| Path::new("")).to_path_buf();
        out.push(ScannedFile { krate, rel, dir, ast });
    }
    out
}

#[derive(Debug, Default)]
struct ScanReport {
    sql_counts: BTreeMap<(String, String), usize>,
    /// Every counted site: `(crate, relative_path, line, what)`, for
    /// `print_generated_baselines` and drift review.
    sites: Vec<(String, String, usize, String)>,
    helpers: BTreeMap<(String, String, String), DetectedHelper>,
    ua_store_pub_sql_fns: BTreeMap<(String, String), DetectedHelper>,
    procedure_counts: BTreeMap<(String, String), usize>,
    procedure_constructors: Vec<(String, String, String, usize)>,
}

/// Collect names of free `fn` items declared in `file` (outside `#[cfg(test)]`)
/// so a file's own non-helper function (e.g. `cycles.rs:fn transition`) shadows
/// a same-named `pub(crate)` SQL helper from another module on unqualified calls.
fn collect_local_fn_names(file: &File) -> BTreeSet<String> {
    struct LocalFnNames(BTreeSet<String>);
    impl<'ast> Visit<'ast> for LocalFnNames {
        fn visit_item(&mut self, node: &'ast Item) {
            if item_has_cfg_test(node) {
                return;
            }
            if let Item::Fn(f) = node {
                self.0.insert(f.sig.ident.to_string());
            }
            visit::visit_item(self, node);
        }
    }
    let mut v = LocalFnNames(BTreeSet::new());
    v.visit_file(file);
    v.0
}

fn analyze(files: &[ScannedFile]) -> ScanReport {
    let _macro_cache = MacroCacheGuard::install();
    let mut report = ScanReport::default();

    // Pre-pass: collect non-private callables per crate so cross-module builders
    // (e.g. `pub(crate) fn filter` in `note.rs` called from `search.rs`) share
    // per-field / per-tuple return taint without private helpers in unrelated
    // modules colliding on common names like `set` or `sql`.
    let mut crate_pub_callables: BTreeMap<String, Vec<CandidateCallable<'_>>> = BTreeMap::new();
    let mut file_callables: Vec<Vec<CandidateCallable<'_>>> = Vec::with_capacity(files.len());
    for f in files {
        let mut col = CallableCollector::new();
        col.visit_file(&f.ast);
        for c in &col.callables {
            if c.vis != HelperVis::Private {
                crate_pub_callables.entry(f.krate.clone()).or_default().push(c.clone());
            }
        }
        file_callables.push(col.callables);
    }

    let crate_pub_ret_taint: BTreeMap<String, Rc<LocalReturnTaint>> = crate_pub_callables
        .into_iter()
        .map(|(k, cs)| (k, Rc::new(compute_local_return_taint(&cs, None))))
        .collect();

    // Step 1: detect direct SQL calls, SQL-taking helpers, procedures, and constructors.
    for (idx, f) in files.iter().enumerate() {
        let base_ret = crate_pub_ret_taint.get(&f.krate).cloned();
        let ret_taint = compute_local_return_taint(&file_callables[idx], base_ret);

        if f.krate == "ua-store" {
            if f.rel != "src/schema.rs" {
                for h in detect_sql_helpers(&f.ast, &ret_taint) {
                    if h.is_pub {
                        report.ua_store_pub_sql_fns.entry((f.rel.clone(), h.name.clone())).or_insert(h);
                    }
                }
            }
            continue;
        }

        let mut direct = DirectSqlCollector::new();
        direct.visit_file(&f.ast);
        let direct_sites = direct.finish();
        let direct_count = direct_sites.len();
        for site in &direct_sites {
            let (line, what) = match site {
                DirectSqlSite::Call(_, line) => (*line, "direct"),
                DirectSqlSite::FnPointer(line) => (*line, "direct (fn pointer)"),
            };
            report.sites.push((f.krate.clone(), f.rel.clone(), line, what.to_string()));
        }
        if direct_count > 0 {
            *report.sql_counts.entry((f.krate.clone(), f.rel.clone())).or_default() += direct_count;
        }

        for h in detect_sql_helpers(&f.ast, &ret_taint) {
            report.helpers.entry((f.krate.clone(), f.rel.clone(), h.name.clone())).or_insert(h);
        }

        let mut proc_scan = ProcedureScanner { literals: 0, constructors: Vec::new() };
        proc_scan.visit_file(&f.ast);
        if proc_scan.literals > 0 {
            report.procedure_counts.insert((f.krate.clone(), f.rel.clone()), proc_scan.literals);
        }
        for (name, line) in proc_scan.constructors {
            report.procedure_constructors.push((f.krate.clone(), f.rel.clone(), name, line));
        }
    }

    // Step 2: count calls (including fn-pointer refs and macro invocations) to
    // every detected helper in its visibility scope.
    let mut helper_defs: Vec<(String, String, PathBuf, DetectedHelper)> = report
        .helpers
        .iter()
        .map(|((krate, rel, _), h)| {
            let dir = files
                .iter()
                .find(|f| &f.krate == krate && &f.rel == rel)
                .map(|f| f.dir.clone())
                .unwrap_or_default();
            (krate.clone(), rel.clone(), dir, h.clone())
        })
        .collect();
    for ((rel, _), h) in &report.ua_store_pub_sql_fns {
        helper_defs.push(("ua-store".to_string(), rel.clone(), PathBuf::new(), h.clone()));
    }

    for f in files {
        if f.krate == "ua-store" {
            continue;
        }
        let mut in_scope_helpers: BTreeMap<String, BTreeSet<HelperKind>> = BTreeMap::new();
        let mut own_file_helpers: BTreeSet<String> = BTreeSet::new();
        for (h_crate, h_rel, h_dir, h) in &helper_defs {
            let in_scope = match h.vis {
                HelperVis::Private => &f.krate == h_crate && &f.rel == h_rel,
                HelperVis::PubSuper => &f.krate == h_crate && &f.dir == h_dir,
                HelperVis::PubCrate => &f.krate == h_crate,
                HelperVis::Pub => true,
            };
            if in_scope {
                in_scope_helpers.entry(h.name.clone()).or_default().insert(h.kind);
                if &f.krate == h_crate && &f.rel == h_rel {
                    own_file_helpers.insert(h.name.clone());
                }
            }
        }
        if !in_scope_helpers.is_empty() {
            let mut counter = HelperCallCounter::new(&in_scope_helpers);
            // Any free `fn` declared in `f` itself that is NOT a SQL helper
            // shadows an identically named helper imported from another module
            // on unqualified single-segment calls.
            for local_fn in collect_local_fn_names(&f.ast) {
                if !own_file_helpers.contains(&local_fn) {
                    counter.local_vars[0].insert(local_fn);
                }
            }
            counter.visit_file(&f.ast);
            let helper_sites = counter.finish();
            let extra = helper_sites.len();
            for (line, name) in helper_sites {
                report.sites.push((f.krate.clone(), f.rel.clone(), line, format!("helper {name}")));
            }
            if extra > 0 {
                *report.sql_counts.entry((f.krate.clone(), f.rel.clone())).or_default() += extra;
            }
        }
    }

    report
}

