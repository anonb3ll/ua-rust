fn type_mentions_ident(ty: &Type, target: &str) -> bool {
    match ty {
        Type::Path(tp) => tp.path.segments.iter().any(|seg| {
            seg.ident == target
                || match &seg.arguments {
                    syn::PathArguments::AngleBracketed(ab) => ab.args.iter().any(|arg| match arg {
                        syn::GenericArgument::Type(t) => type_mentions_ident(t, target),
                        _ => false,
                    }),
                    syn::PathArguments::Parenthesized(p) => {
                        p.inputs.iter().any(|t| type_mentions_ident(t, target))
                            || matches!(&p.output, ReturnType::Type(_, t) if type_mentions_ident(t, target))
                    }
                    syn::PathArguments::None => false,
                }
        }),
        Type::Reference(r) => type_mentions_ident(&r.elem, target),
        Type::Tuple(t) => t.elems.iter().any(|e| type_mentions_ident(e, target)),
        Type::Slice(s) => type_mentions_ident(&s.elem, target),
        Type::Array(a) => type_mentions_ident(&a.elem, target),
        Type::Paren(p) => type_mentions_ident(&p.elem, target),
        Type::Group(g) => type_mentions_ident(&g.elem, target),
        Type::ImplTrait(it) => it.bounds.iter().any(|b| matches!(b, syn::TypeParamBound::Trait(tb) if tb.path.segments.iter().any(|s| s.ident == target))),
        _ => false,
    }
}

fn macro_body_contains_procedure_literal(stream: TokenStream) -> bool {
    let tts: Vec<TokenTree> = stream.into_iter().collect();
    for (i, tt) in tts.iter().enumerate() {
        if let TokenTree::Ident(id) = tt
            && id == "Procedure"
            && let Some(TokenTree::Group(g)) = tts.get(i + 1)
            && g.delimiter() == Delimiter::Brace
        {
            return true;
        }
        if let TokenTree::Group(g) = tt
            && macro_body_contains_procedure_literal(g.stream())
        {
            return true;
        }
    }
    false
}

struct ProcedureScanner {
    literals: usize,
    constructors: Vec<(String, usize)>,
}

impl<'ast> Visit<'ast> for ProcedureScanner {
    fn visit_item(&mut self, node: &'ast Item) {
        if item_has_cfg_test(node) {
            return;
        }
        visit::visit_item(self, node);
    }

    fn visit_impl_item(&mut self, node: &'ast syn::ImplItem) {
        if impl_item_has_cfg_test(node) {
            return;
        }
        visit::visit_impl_item(self, node);
    }

    fn visit_trait_item(&mut self, node: &'ast syn::TraitItem) {
        if trait_item_has_cfg_test(node) {
            return;
        }
        visit::visit_trait_item(self, node);
    }

    fn visit_expr_struct(&mut self, node: &'ast ExprStruct) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        if node.path.segments.last().is_some_and(|s| s.ident == "Procedure") {
            self.literals += 1;
        }
        visit::visit_expr_struct(self, node);
    }

    fn visit_item_fn(&mut self, node: &'ast ItemFn) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        if let ReturnType::Type(_, ty) = &node.sig.output
            && type_mentions_ident(ty, "Procedure")
        {
            self.constructors.push((node.sig.ident.to_string(), node.sig.ident.span().start().line));
        }
        visit::visit_item_fn(self, node);
    }

    fn visit_impl_item_fn(&mut self, node: &'ast ImplItemFn) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        if let ReturnType::Type(_, ty) = &node.sig.output
            && type_mentions_ident(ty, "Procedure")
        {
            self.constructors.push((node.sig.ident.to_string(), node.sig.ident.span().start().line));
        }
        visit::visit_impl_item_fn(self, node);
    }

    fn visit_trait_item_fn(&mut self, node: &'ast TraitItemFn) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        if let ReturnType::Type(_, ty) = &node.sig.output
            && type_mentions_ident(ty, "Procedure")
        {
            self.constructors.push((node.sig.ident.to_string(), node.sig.ident.span().start().line));
        }
        visit::visit_trait_item_fn(self, node);
    }

    fn visit_item_macro(&mut self, node: &'ast ItemMacro) {
        if attrs_have_cfg_test(&node.attrs) {
            return;
        }
        if node.mac.path.is_ident("macro_rules")
            && let Some(ident) = &node.ident
        {
            for body in extract_macro_rule_bodies(node.mac.tokens.clone()) {
                if macro_body_contains_procedure_literal(body) {
                    self.constructors.push((format!("{}!", ident), ident.span().start().line));
                    break;
                }
            }
        }
    }
}

