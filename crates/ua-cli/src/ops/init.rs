//! `ua init`: initialize `$UA_HOME/config.toml`, optional starter `policy.yaml`,
//! local harness discovery + MCP client snippets, and optional initial token.

use std::fmt::Write as _;
use std::fs::{self, OpenOptions};
use std::io::Write as _;
use std::path::{Path, PathBuf};

use anyhow::{Context, bail};
use clap::Args;
use serde::Serialize;
use serde_json::{Value, json};
use ua_core::Config;
use ua_tools::Hub;

use super::{
    backup_existing_file, default_home, ensure_dir_private, expand_tilde, reject_if_symlink,
    set_owner_only_file, write_atomic_file,
};

const KNOWN_HARNESSES: [(&str, &str); 6] = [
    ("claude", "claude"),
    ("codex", "codex"),
    ("cursor", "cursor"),
    ("opencode", "opencode"),
    ("pi", "pi"),
    ("gemini", "gemini"),
];

#[derive(Debug, Clone, Args)]
pub struct InitArgs {
    /// Hub data directory (default: $UA_HOME or ~/.ua-rust).
    #[arg(long)]
    pub home: Option<PathBuf>,
    /// Workspace root confined for file/command tools (default: <home>/workspace).
    #[arg(long)]
    pub workspace: Option<PathBuf>,
    /// Initial human operator identity label.
    #[arg(long, default_value = "operator")]
    pub operator: String,
    /// Optional agent identity to mint a first bearer token for (token printed once).
    #[arg(long)]
    pub agent: Option<String>,
    /// Also write a starter `<home>/policy.yaml` and link it via `policy_file`.
    #[arg(long)]
    pub with_policy: bool,
    /// Overwrite an existing config.toml or policy.yaml (saves `.bak-*` copies first).
    #[arg(long)]
    pub force: bool,
    /// Print structured JSON instead of a human summary.
    #[arg(long)]
    pub json: bool,
}

#[derive(Debug, Clone, Serialize)]
pub struct DetectedHarness {
    pub name: String,
    pub binary: String,
    pub path: String,
}

#[derive(Debug, Clone, Serialize)]
pub struct McpSnippets {
    pub http_url: String,
    pub stdio_command: String,
    pub mcp_servers_json: Value,
    pub claude_cli_http: String,
}

#[derive(Debug, Clone, Serialize)]
pub struct IssuedToken {
    pub agent: String,
    pub token: String,
}

#[derive(Debug, Clone, Serialize)]
pub struct InitReport {
    pub home: String,
    pub config_path: String,
    pub workspace: String,
    pub policy_path: Option<String>,
    pub operator: String,
    pub backed_up_files: Vec<String>,
    pub detected_harnesses: Vec<DetectedHarness>,
    pub mcp_snippets: McpSnippets,
    pub issued_token: Option<IssuedToken>,
}

fn toml_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 || c as u32 == 0x7f => {
                let _ = write!(out, "\\u{:04x}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn render_config_toml(
    home: &Path,
    workspace: &Path,
    operator: &str,
    agent: Option<&str>,
    policy_path: Option<&Path>,
) -> String {
    let mut out = String::new();
    out.push_str("# Generated by `ua init`.\n");
    out.push_str("# UA_* environment variables override settings in this file.\n\n");
    let _ = writeln!(out, "home = {}", toml_string(&home.display().to_string()));
    let _ = writeln!(out, "workspace = {}", toml_string(&workspace.display().to_string()));
    if let Some(p) = policy_path {
        let _ = writeln!(out, "policy_file = {}", toml_string(&p.display().to_string()));
    }
    out.push_str("read_roots = []\n\n");
    out.push_str("bind = \"127.0.0.1:8765\"\n");
    out.push_str("enforce_auth = true\n");
    out.push_str("allowed_hosts = [\"localhost\", \"127.0.0.1\", \"::1\"]\n\n");
    let _ = writeln!(out, "human_identities = [{}]", toml_string(operator));
    out.push_str("approval_tools = [\"git_merge_task\"]\n");
    out.push_str("routines_enabled = false\n\n");
    out.push_str("[profiles]\n");
    let _ = writeln!(out, "{} = \"operator\"", toml_string(operator));
    if let Some(a) = agent.filter(|a| *a != operator) {
        let _ = writeln!(out, "{} = \"developer\"", toml_string(a));
    }
    out
}

fn starter_policy_yaml() -> &'static str {
    "# Starter policy for ua-rust (see docs/policy.md).\n\
version: 1\n\
enabled: true\n\
default_action: allow\n\
\n\
rules:\n\
  - name: approve-task-delete\n\
    type: tool\n\
    tool: \"task_delete\"\n\
    action: require_approval\n\
    description: Deleting tasks requires human approval.\n"
}

fn is_executable(path: &Path) -> bool {
    let Ok(meta) = fs::metadata(path) else { return false };
    if !meta.is_file() {
        return false;
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        meta.permissions().mode() & 0o111 != 0
    }
    #[cfg(not(unix))]
    {
        true
    }
}

/// Detect known coding-agent CLIs on `PATH` without spawning subprocesses.
pub fn detect_harnesses() -> Vec<DetectedHarness> {
    let Some(path_var) = std::env::var_os("PATH") else {
        return Vec::new();
    };
    let dirs: Vec<PathBuf> = std::env::split_paths(&path_var).collect();
    let mut found = Vec::new();
    for (name, bin) in KNOWN_HARNESSES {
        for dir in &dirs {
            let candidate = dir.join(bin);
            if is_executable(&candidate) {
                found.push(DetectedHarness {
                    name: name.to_string(),
                    binary: bin.to_string(),
                    path: candidate.display().to_string(),
                });
                break;
            }
        }
    }
    found
}

fn build_snippets(bind: std::net::SocketAddr, agent_label: &str) -> McpSnippets {
    let http_url = format!("http://{bind}/mcp");
    let stdio_command = format!("ua mcp --label {agent_label}");
    let mcp_servers_json = json!({
        "mcpServers": {
            "ua-rust": {
                "type": "http",
                "url": http_url,
                "headers": {
                    "Authorization": "Bearer <UA_BEARER_TOKEN>"
                }
            }
        }
    });
    let claude_cli_http = format!(
        "claude mcp add --transport http ua-rust {http_url} --header \"Authorization: Bearer <UA_BEARER_TOKEN>\""
    );
    McpSnippets { http_url, stdio_command, mcp_servers_json, claude_cli_http }
}

struct TempConfigGuard {
    path: PathBuf,
}

impl TempConfigGuard {
    fn create(dir: &Path, toml_text: &str) -> anyhow::Result<Self> {
        let path = dir.join(format!(".config.{}.toml.tmp", std::process::id()));
        let _ = fs::remove_file(&path);
        let mut opts = OpenOptions::new();
        opts.write(true).create_new(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            opts.mode(0o600);
            opts.custom_flags(libc::O_NOFOLLOW);
        }
        let mut f = opts.open(&path)?;
        f.write_all(toml_text.as_bytes())?;
        f.sync_all()?;
        Ok(Self { path })
    }
}

impl Drop for TempConfigGuard {
    fn drop(&mut self) {
        let _ = fs::remove_file(&self.path);
    }
}

/// `allow_newer_schema`: open a database written by a newer build anyway when
/// minting the initial token (`--allow-newer-schema`), as the other commands do.
pub fn run(args: InitArgs, explicit_config: Option<&Path>, allow_newer_schema: bool) -> anyhow::Result<()> {
    run_inner(args, explicit_config, None, allow_newer_schema)
}

fn run_inner(
    args: InitArgs,
    explicit_config: Option<&Path>,
    before_config_write: Option<&dyn Fn() -> anyhow::Result<()>>,
    allow_newer_schema: bool,
) -> anyhow::Result<()> {
    let operator = args.operator.trim().to_string();
    if operator.is_empty() {
        bail!("--operator label must not be empty");
    }
    let agent = args.agent.as_deref().map(str::trim).filter(|s| !s.is_empty()).map(str::to_string);
    if args.agent.is_some() && agent.is_none() {
        bail!("--agent label must not be empty");
    }

    let raw_home = args
        .home
        .clone()
        .or_else(|| std::env::var_os("UA_HOME").map(PathBuf::from))
        .unwrap_or_else(default_home);
    let home = expand_tilde(&raw_home);
    ua_store::backup::check_dir_owner(&home)?;

    let config_path = match explicit_config {
        Some(p) if args.home.is_none() => expand_tilde(p),
        _ => home.join("config.toml"),
    };
    let workspace = args.workspace.as_deref().map(expand_tilde).unwrap_or_else(|| home.join("workspace"));
    let policy_path = args.with_policy.then(|| home.join("policy.yaml"));

    reject_if_symlink(&config_path, "config")?;
    if !args.force && fs::symlink_metadata(&config_path).is_ok() {
        bail!("config {} already exists (pass --force to overwrite)", config_path.display());
    }
    if let Some(p) = &policy_path {
        reject_if_symlink(p, "policy")?;
        if !args.force && fs::symlink_metadata(p).is_ok() {
            bail!("policy {} already exists (pass --force to overwrite)", p.display());
        }
    }

    ensure_dir_private(&home)?;
    ensure_dir_private(&workspace)?;

    if policy_path.is_some()
        && let Err(e) = ua_tools::policy::parse_policy(starter_policy_yaml())
    {
        bail!("internal error validating starter policy: {e}");
    }

    let toml_text =
        render_config_toml(&home, &workspace, &operator, agent.as_deref(), policy_path.as_deref());
    let staged_cfg = TempConfigGuard::create(&home, &toml_text)?;
    let mut cfg = Config::load_from(&staged_cfg.path)?;
    if args.home.is_some() {
        cfg.home = home.clone();
        cfg.db_path = None;
    }
    if args.workspace.is_some() {
        cfg.workspace = Some(workspace.clone());
    }

    // Mint the initial token BEFORE installing `config.toml` / `policy.yaml` so a
    // refused interactive human TTY check or lock leaves existing config untouched.
    // If installing config/policy subsequently fails, roll back any `.bak-*` files
    // and revoke the newly minted token so no unshown active token is left behind.
    let mut minted_context: Option<(Hub, i64, String)> = None;
    let issued_token = if let Some(agent_label) = agent.as_deref() {
        let db_path = cfg.db_path();
        let _lock = ua_import::HubLock::acquire_shared(&db_path, "init")?;
        let hub = Hub::open_with(cfg.clone(), allow_newer_schema)?;
        let prev_max_id: i64 = hub
            .db()
            .read(|c| Ok(c.query_row("SELECT COALESCE(MAX(id), 0) FROM agent_tokens", [], |r| r.get(0))?))
            .context("reading agent_tokens high-water mark before minting initial token")?;
        let token = crate::issue_agent_token(&cfg, &hub, agent_label, Some("ua init"), "cli")?;
        set_owner_only_file(&db_path)?;
        minted_context = Some((hub, prev_max_id, agent_label.to_string()));
        Some(IssuedToken { agent: agent_label.to_string(), token })
    } else {
        None
    };

    drop(staged_cfg);

    let mut backed_up_files: Vec<String> = Vec::new();
    let mut restore_pairs: Vec<(PathBuf, PathBuf)> = Vec::new();
    let mut created_files: Vec<PathBuf> = Vec::new();
    let install_res = (|| -> anyhow::Result<()> {
        if args.force {
            if let Some(bak) = backup_existing_file(&config_path)? {
                backed_up_files.push(bak.display().to_string());
                restore_pairs.push((bak, config_path.clone()));
            }
            if let Some(p) = &policy_path
                && let Some(bak) = backup_existing_file(p)?
            {
                backed_up_files.push(bak.display().to_string());
                restore_pairs.push((bak, p.clone()));
            }
        }

        if let Some(p) = &policy_path {
            let had_backup = restore_pairs.iter().any(|(_, orig)| orig == p);
            write_atomic_file(p, starter_policy_yaml().as_bytes(), args.force)?;
            if !had_backup {
                created_files.push(p.clone());
            }
        }
        if let Some(hook) = before_config_write {
            hook()?;
        }
        write_atomic_file(&config_path, toml_text.as_bytes(), args.force)?;
        Ok(())
    })();

    if let Err(err) = install_res {
        for created in created_files.iter().rev() {
            let _ = fs::remove_file(created);
        }
        for (bak, orig) in restore_pairs.iter().rev() {
            let _ = fs::rename(bak, orig);
        }
        let mut revoke_note = String::new();
        if let Some((hub, prev_max_id, label)) = minted_context {
            let now = ua_core::time::now();
            let rev = hub.db().write(|tx| {
                let changed = tx.execute(
                    "UPDATE agent_tokens SET status = 'revoked', revoked_at = ?1 \
                     WHERE id > ?2 AND agent_label = ?3 AND status = 'active'",
                    rusqlite::params![&now, prev_max_id, &label],
                )?;
                if changed > 0 {
                    ua_store::ledger::append(
                        tx,
                        ua_store::EventInput::new(
                            ua_core::DEFAULT_ORG,
                            "agent.token.revoked",
                            json!({ "agent": &label, "reason": "ua_init_failed", "revoked_at": &now }),
                        )
                        .by("cli"),
                    )?;
                }
                Ok(changed)
            });
            if matches!(rev, Ok(n) if n > 0) {
                revoke_note = format!(" (revoked unshown initial token for `{label}`)");
            } else {
                revoke_note = format!(
                    " (warning: initial token for `{label}` was committed before write failed; inspect with `ua token`)"
                );
            }
        }
        return Err(err.context(format!("installing hub configuration files{revoke_note}")));
    }

    let detected_harnesses = detect_harnesses();
    let mcp_snippets = build_snippets(cfg.bind, agent.as_deref().unwrap_or("builder-1"));
    let report = InitReport {
        home: home.display().to_string(),
        config_path: config_path.display().to_string(),
        workspace: workspace.display().to_string(),
        policy_path: policy_path.map(|p| p.display().to_string()),
        operator,
        backed_up_files,
        detected_harnesses,
        mcp_snippets,
        issued_token,
    };

    if args.json {
        println!("{}", serde_json::to_string_pretty(&report)?);
    } else {
        println!("Initialized ua-rust hub in {}", report.home);
        println!("  config:    {}", report.config_path);
        println!("  workspace: {}", report.workspace);
        if let Some(p) = &report.policy_path {
            println!("  policy:    {p}");
        }
        for b in &report.backed_up_files {
            println!("  backup:    {b}");
        }
        if let Some(tok) = &report.issued_token {
            println!("  token ({}, shown once): {}", tok.agent, tok.token);
        }
        if report.detected_harnesses.is_empty() {
            println!("  harnesses: none found on PATH");
        } else {
            let names: Vec<&str> = report.detected_harnesses.iter().map(|h| h.name.as_str()).collect();
            println!("  harnesses: {}", names.join(", "));
        }
        println!("\nNext steps:");
        println!("  1. ua doctor");
        if report.issued_token.is_none() {
            println!("  2. ua token issue builder-1");
            println!("  3. ua serve");
            println!("  4. ua login-link {}", report.operator);
        } else {
            println!("  2. ua serve");
            println!("  3. ua login-link {}", report.operator);
        }
        println!("\nMCP Streamable HTTP: {}", report.mcp_snippets.http_url);
        println!("MCP stdio:           {}", report.mcp_snippets.stdio_command);
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use rusqlite::{Connection, OpenFlags};

    fn test_args(home: &Path, agent: Option<&str>, with_policy: bool, force: bool) -> InitArgs {
        InitArgs {
            home: Some(home.to_path_buf()),
            workspace: Some(home.join("workspace")),
            operator: "operator".into(),
            agent: agent.map(str::to_string),
            with_policy,
            force,
            json: true,
        }
    }

    #[test]
    fn install_failure_revokes_only_newly_minted_token_and_cleans_created_policy() {
        let dir = tempfile::tempdir().unwrap();
        let home = dir.path().join("hub-home");
        ensure_dir_private(&home).unwrap();

        // Pre-seed an active token for the same label before `ua init` fails.
        let mut seed_cfg = Config::for_home(&home);
        seed_cfg.db_path = None;
        let hub = Hub::open(seed_cfg.clone()).unwrap();
        crate::issue_agent_token(&seed_cfg, &hub, "builder-1", Some("pre-existing"), "cli").unwrap();
        drop(hub);

        let err = run_inner(
            test_args(&home, Some("builder-1"), true, false),
            None,
            Some(&|| bail!("simulated config install failure")),
            false,
        )
        .unwrap_err();
        let msg = format!("{err:#}");
        assert!(msg.contains("revoked unshown initial token"), "{msg}");

        // Non-`--force` starter policy must not remain behind to block retry.
        assert!(!home.join("policy.yaml").exists(), "policy.yaml leaked after failed init");
        assert!(!home.join("config.toml").exists(), "config.toml should not exist");

        let conn = Connection::open_with_flags(
            seed_cfg.db_path(),
            OpenFlags::SQLITE_OPEN_READ_ONLY | OpenFlags::SQLITE_OPEN_NO_MUTEX,
        )
        .unwrap();
        let statuses: Vec<(i64, String)> = {
            let mut stmt = conn
                .prepare("SELECT id, status FROM agent_tokens WHERE agent_label = 'builder-1' ORDER BY id")
                .unwrap();
            stmt.query_map([], |r| Ok((r.get(0)?, r.get(1)?))).unwrap().map(Result::unwrap).collect()
        };
        assert_eq!(statuses.len(), 2, "expected pre-existing + revoked newly minted token: {statuses:?}");
        assert_eq!(statuses[0].1, "active", "pre-existing token was unexpectedly revoked: {statuses:?}");
        assert_eq!(statuses[1].1, "revoked", "newly minted token stayed active: {statuses:?}");

        let revoked_events: i64 = conn
            .query_row("SELECT COUNT(*) FROM event_log WHERE channel = 'agent.token.revoked'", [], |r| {
                r.get(0)
            })
            .unwrap();
        assert_eq!(revoked_events, 1);
        assert!(ua_store::ledger::verify(&conn).unwrap().ok);
        drop(conn);

        // Retrying without `--force` must succeed because failed init left no stale files.
        run_inner(test_args(&home, None, true, false), None, None, false).unwrap();
        assert!(home.join("policy.yaml").is_file());
        assert!(home.join("config.toml").is_file());
    }

    #[test]
    fn force_install_failure_restores_previous_config_and_revokes_token() {
        let dir = tempfile::tempdir().unwrap();
        let home = dir.path().join("hub-home");
        ensure_dir_private(&home).unwrap();
        let config_path = home.join("config.toml");
        fs::write(&config_path, "# sentinel original config\n").unwrap();

        let err = run_inner(
            test_args(&home, Some("builder-1"), false, true),
            None,
            Some(&|| bail!("simulated force write failure")),
            false,
        )
        .unwrap_err();
        let msg = format!("{err:#}");
        assert!(msg.contains("revoked unshown initial token"), "{msg}");
        assert_eq!(fs::read_to_string(&config_path).unwrap(), "# sentinel original config\n");

        let conn = Connection::open_with_flags(
            home.join("ua.db"),
            OpenFlags::SQLITE_OPEN_READ_ONLY | OpenFlags::SQLITE_OPEN_NO_MUTEX,
        )
        .unwrap();
        let active: i64 = conn
            .query_row("SELECT COUNT(*) FROM agent_tokens WHERE status = 'active'", [], |r| r.get(0))
            .unwrap();
        assert_eq!(active, 0);
        assert!(ua_store::ledger::verify(&conn).unwrap().ok);
    }
}
